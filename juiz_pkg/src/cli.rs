//! コマンドライン (`juiz-pkg` と `juiz pkg` で同じ引数を使う、docs/spec/pkg.md §2)

use std::path::PathBuf;

use clap::{Args, Subcommand, ValueEnum};

use crate::add::AddKind;
use crate::design::plugin::PluginLoader;
use crate::{Lang, PkgError, Template};

/// 雛形を作る (juiz pkg / juiz-pkg)
#[derive(Args, Clone, Debug)]
pub struct PkgArgs {
    #[command(subcommand)]
    pub command: PkgCommand,
}

#[derive(Subcommand, Clone, Debug)]
pub enum PkgCommand {
    /// Create a new package skeleton (a Component that can be packed into a .juizapp as is)
    Create(CreateArgs),
    /// Add a Process or a Container to a skeleton made by `juiz pkg create` (edits the Component source and app/app.conf)
    Add(AddArgs),
    /// Print the host target triple (the <target> of app/plugins/<target>/)
    Target,
    /// Write a design document (juizdesign.yaml) of a Component without making a skeleton, or check one
    Design(DesignArgs),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, ValueEnum)]
pub enum LicenseKind {
    /// Put LICENSE-MIT and LICENSE-APACHE (MIT OR Apache-2.0)
    MitApache,
    /// No license files
    None,
}

#[derive(Args, Clone, Debug)]
pub struct CreateArgs {
    /// Package name ([a-z][a-z0-9_]*). Used as the Component name and the prefix of type names
    #[arg(required_unless_present = "design")]
    pub name: Option<String>,

    /// Language (with -d: default component.language of the design document)
    #[arg(short = 'b', long = "lang", ignore_case = true, required_unless_present = "design")]
    pub lang: Option<Lang>,

    /// What to put in the Component
    #[arg(short = 't', long = "template", default_value = "component", ignore_case = true)]
    pub template: Template,

    /// Make typed functions from the process / container declarations of this .jidl instead of the
    /// example types. The .jidl is copied to idl/ and its types are generated by the build
    #[arg(long = "idl", value_name = "FILE.jidl", conflicts_with = "template")]
    pub idl: Option<PathBuf>,

    /// Make the skeleton from this design document (juizdesign.yaml): the name is component.name of it,
    /// and the bodies of the functions are left to write (Rust and Python in this version)
    #[arg(short = 'd', long = "design", value_name = "FILE", conflicts_with_all = ["name", "template", "idl"])]
    pub design: Option<PathBuf>,

    /// Directory to create (default: ./<name>). It must not exist, or be empty
    #[arg(short = 'o', long = "output")]
    pub output: Option<PathBuf>,

    /// License files to put
    #[arg(long = "license", default_value = "none")]
    pub license: LicenseKind,

    /// Copyright holder for --license mit-apache (default: git config user.name)
    #[arg(long = "author")]
    pub author: Option<String>,

    /// Haskell only: hsjuiz source directory (default: ~/juiz-<version>/bindings/hsjuiz)
    #[arg(long = "hsjuiz-dir")]
    pub hsjuiz_dir: Option<PathBuf>,

    /// Zig only: zigjuiz source directory. build.zig.zon points to it with a path relative to the skeleton
    /// (default: none; scripts/dev.sh gets zigjuiz <version> from the GitHub release with zig fetch)
    #[arg(long = "zigjuiz-dir")]
    pub zigjuiz_dir: Option<PathBuf>,

    /// C++, Haskell and Zig only: libjuiz_sdk directory (default: ~/.juiz/sdk/<version>)
    #[arg(long = "juiz-sdk-dir")]
    pub juiz_sdk_dir: Option<PathBuf>,

    /// For juiz developers: use the juiz sources in this repository instead of the published SDK
    #[arg(long = "juiz-source")]
    pub juiz_source: Option<PathBuf>,
}

/// `juiz pkg design <name>` と `juiz pkg design check <file>` (pkg.md §2.6・§2.7)
#[derive(Args, Clone, Debug)]
#[command(args_conflicts_with_subcommands = true, subcommand_negates_reqs = true)]
pub struct DesignArgs {
    #[command(subcommand)]
    pub command: Option<DesignCommand>,

    /// Component name ([a-z][a-z0-9_]*). With --from-plugin: default the name of the plugin's Component
    #[arg(required_unless_present = "from_plugin")]
    pub name: Option<String>,

    /// Language: written as component.language, and its rules are checked too
    #[arg(short = 'b', long = "lang", ignore_case = true)]
    pub lang: Option<Lang>,

    /// Which preset design to write (the same types as juiz pkg create -t)
    #[arg(short = 't', long = "template", default_value = "component", ignore_case = true)]
    pub template: Template,

    /// Write the types of the process / container declarations of this .jidl instead of a preset.
    /// The .jidl must be in the directory of the document (idl: refers to it by a relative path)
    #[arg(long = "idl", value_name = "FILE.jidl", conflicts_with = "template")]
    pub idl: Option<PathBuf>,

    /// Write the types of this built plugin (its manifest) instead of a preset. The language of the plugin is
    /// -b (a .py file is Python without -b). Its record and enum types are written to idl/<name>.jidl beside the document
    #[arg(long = "from-plugin", value_name = "PLUGIN", conflicts_with_all = ["template", "idl"])]
    pub from_plugin: Option<PathBuf>,

    /// File to write (default: ./juizdesign.yaml). It must not exist
    #[arg(short = 'o', long = "output")]
    pub output: Option<PathBuf>,
}

#[derive(Subcommand, Clone, Debug)]
pub enum DesignCommand {
    /// Check a design document (juizdesign.yaml) and print all the errors
    Check(DesignCheckArgs),
}

#[derive(Args, Clone, Debug)]
pub struct DesignCheckArgs {
    /// Design document to check
    pub file: PathBuf,

    /// Language whose rules are checked too (default: component.language of the document)
    #[arg(short = 'b', long = "lang", ignore_case = true)]
    pub lang: Option<Lang>,

    /// Also check that this built plugin has the types of the document (its manifest matches the document).
    /// The plugin is opened as the language of -b or component.language (a .py file is Python)
    #[arg(long = "plugin", value_name = "PLUGIN")]
    pub plugin: Option<PathBuf>,
}

#[derive(Args, Clone, Debug)]
pub struct AddArgs {
    /// What to add: process (<name>) or container (<name> with <name>_increment and <name>_get)
    #[arg(ignore_case = true)]
    pub kind: AddKind,

    /// Type name ([a-z][a-z0-9_]*)
    pub name: String,

    /// Skeleton directory (the one with app/app.conf)
    #[arg(short = 'C', long = "dir", default_value = ".")]
    pub dir: PathBuf,
}

/// サブコマンドを実行する。プラグインを開くもの (`design check --plugin`・`design --from-plugin`) はエラーになる
/// (juiz-pkg 単体。juiz は [`run_with`] で開く関数を渡す)
pub fn run(args: &PkgArgs) -> Result<(), PkgError> {
    run_with(args, &crate::design::plugin::no_loader)
}

/// サブコマンドを実行する。`loader` はプラグインを開いて ComponentManifest を読む関数 (design.md §8.5・§8.6)
pub fn run_with(args: &PkgArgs, loader: PluginLoader) -> Result<(), PkgError> {
    match &args.command {
        PkgCommand::Create(c) => {
            let created = crate::create::create(c)?;
            for w in &created.warnings {
                eprintln!("warning: {w}");
            }
            print!("{}", created.summary);
            Ok(())
        }
        PkgCommand::Add(a) => {
            let added = crate::add::add(a)?;
            for w in &added.warnings {
                eprintln!("warning: {w}");
            }
            print!("{}", added.summary);
            Ok(())
        }
        PkgCommand::Target => {
            println!("{}", crate::HOST_TARGET);
            Ok(())
        }
        PkgCommand::Design(d) => match (&d.command, &d.name) {
            (Some(DesignCommand::Check(c)), _) => {
                let checked = crate::design::command::check_file(c, loader)?;
                for l in &checked.lines {
                    eprintln!("{l}");
                }
                match &checked.ok_line {
                    Some(ok) => {
                        println!("{ok}");
                        Ok(())
                    }
                    None => Err(PkgError::new(format!(
                        "{} is not a valid design document ({} error{})",
                        c.file.display(),
                        checked.report.errors.len(),
                        if checked.report.errors.len() == 1 { "" } else { "s" }
                    ))),
                }
            }
            (None, name) if name.is_some() || d.from_plugin.is_some() => {
                let written = crate::design::command::design(name.as_deref(), d, loader)?;
                for w in &written.warnings {
                    eprintln!("warning: {w}");
                }
                print!("{}", written.summary);
                Ok(())
            }
            (None, _) => Err(PkgError::new("give a component name: juiz pkg design <name>")),
        },
    }
}
