//! Python のコードの書き出し (仕様 §11・§20、issue #194)
//!
//! 名前空間 `a.b` ごとにパッケージ `a/b/__init__.py` を作る (途中の `a/__init__.py` も作る)。
//! 中身は次のもの。値の変換と型参照は pyjuiz の `juiz.datatype` が受け持つ。
//!
//! - record は `@dataclasses.dataclass(kw_only=True)`、enum は `enum.Enum` (値は記号の文字列)。
//!   どちらも `to_value` / `from_value` / `type_schema` と、型参照 `__juiz_type__` (.avsc と同じスキーマと指紋) を持つ。
//! - `process` 宣言は `<型名の CamelCase>Client`、`container` 宣言は `<型名の CamelCase>Client` の型付き client stub
//!   (`juiz.proxy` の ProcessProxy / ContainerProxy を包む)。
//!
//! ほかの名前空間の型は `import a.b as _ns_a_b` で参照する。出力先のディレクトリを `sys.path` (juiz の conf の
//! `option.pythonpath` など) に入れて使う。

use std::collections::{BTreeMap, BTreeSet};

use juiz_types::{DataType, TypeSchema};
use serde_json::Value;

use crate::constants::record_constants;
use crate::{key_rank, ContainerSignature, GeneratedFile, IdlError, ProcessSignature, Signatures};

pub(crate) const HEADER: &str =
    "# @generated by juiz-idl. 手で直さないこと (元の .jidl / .avsc を直して作り直す)\n";

const KEYWORDS: [&str; 35] = [
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield",
];

/// 生成した record / enum のメソッドの名前。フィールド名・記号と同じなら末尾に `_` を付ける
const METHODS: [&str; 3] = ["to_value", "from_value", "type_schema"];

/// enum.Enum の記号にできない名前 (Enum の属性とぶつかる)
const ENUM_RESERVED: [&str; 1] = ["mro"];

/// client stub の属性の名前。container_process の名前には使えない
const CLIENT_ATTRIBUTES: [&str; 3] = ["proxy", "type_name", "connect"];

fn generate_error(message: String) -> IdlError {
    IdlError::Generate { message }
}

/// フィールド名・記号・引数名を Python の識別子にする。キーワードと `reserved` は末尾に `_` を付ける
fn ident(name: &str, reserved: &[&str]) -> String {
    if KEYWORDS.contains(&name) || reserved.contains(&name) {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

/// 型の名前・パッケージの名前。キーワードと、生成したコードが使う `_` で始まる名前は使えない
fn type_ident(name: &str) -> Result<String, IdlError> {
    if KEYWORDS.contains(&name) || name.starts_with('_') {
        return Err(generate_error(format!(
            "'{name}' cannot be used as a Python type or package name"
        )));
    }
    Ok(name.to_owned())
}

/// 名前空間のモジュールの別名 (`a.b` → `_ns_a_b`)
fn namespace_alias(namespace: &str) -> String {
    format!("_ns_{}", namespace.replace('.', "_"))
}

fn named(t: &DataType) -> (&str, &str) {
    match t {
        DataType::Record(r) => (&r.namespace, &r.name),
        DataType::Enum(e) => (&e.namespace, &e.name),
        _ => unreachable!(),
    }
}

/// モジュール `from_namespace` から見た名前付き型の名前
fn named_ref(
    t: &DataType,
    from_namespace: &str,
    imports: &mut BTreeSet<String>,
) -> Result<String, IdlError> {
    let (namespace, name) = named(t);
    let name = type_ident(name)?;
    if namespace == from_namespace {
        return Ok(name);
    }
    imports.insert(namespace.to_owned());
    Ok(format!("{}.{name}", namespace_alias(namespace)))
}

/// 型注釈 (`from __future__ import annotations` の下で書く)
fn annotation(t: &DataType, ns: &str, imports: &mut BTreeSet<String>) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Null => "None".to_owned(),
        DataType::Boolean => "bool".to_owned(),
        DataType::Int | DataType::Long => "int".to_owned(),
        DataType::Float | DataType::Double => "float".to_owned(),
        DataType::String => "str".to_owned(),
        DataType::Bytes => "bytes".to_owned(),
        DataType::Array(items) => format!("list[{}]", annotation(items, ns, imports)?),
        DataType::Map(values) => format!("dict[str, {}]", annotation(values, ns, imports)?),
        DataType::Optional { inner, .. } => format!("{} | None", annotation(inner, ns, imports)?),
        DataType::Record(_) | DataType::Enum(_) => named_ref(t, ns, imports)?,
        DataType::Any => "_typing.Any".to_owned(),
        DataType::Image => {
            imports.insert(PIL_IMPORT.to_owned());
            "_PILImage.Image".to_owned()
        }
    })
}

/// `imports` に入れると `import PIL.Image as _PILImage` を書く
const PIL_IMPORT: &str = "PIL.Image";

/// `juiz.datatype` の変換器の式
fn converter(t: &DataType, ns: &str, imports: &mut BTreeSet<String>) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Null => "_jt.Null".to_owned(),
        DataType::Boolean => "_jt.Boolean".to_owned(),
        DataType::Int => "_jt.Int".to_owned(),
        DataType::Long => "_jt.Long".to_owned(),
        DataType::Float => "_jt.Float".to_owned(),
        DataType::Double => "_jt.Double".to_owned(),
        DataType::String => "_jt.String".to_owned(),
        DataType::Bytes => "_jt.Bytes".to_owned(),
        DataType::Array(items) => format!("_jt.Array({})", converter(items, ns, imports)?),
        DataType::Map(values) => format!("_jt.Map({})", converter(values, ns, imports)?),
        DataType::Optional { inner, .. } => {
            format!("_jt.Optional({})", converter(inner, ns, imports)?)
        }
        DataType::Record(_) => format!("_jt.Record(lambda: {})", named_ref(t, ns, imports)?),
        DataType::Enum(_) => format!("_jt.Enum(lambda: {})", named_ref(t, ns, imports)?),
        DataType::Any => "_jt.Any".to_owned(),
        DataType::Image => "_jt.Image".to_owned(),
    })
}

/// Python の文字列リテラル ("…")
fn str_lit(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                out.push_str(&format!("\\x{:02x}", c as u32))
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// JSON の値の Python のリテラル (1 行)
fn literal(v: &Value) -> String {
    match v {
        Value::Null => "None".to_owned(),
        Value::Bool(true) => "True".to_owned(),
        Value::Bool(false) => "False".to_owned(),
        Value::Number(n) => n.to_string(),
        Value::String(s) => str_lit(s),
        Value::Array(a) => format!("[{}]", a.iter().map(literal).collect::<Vec<_>>().join(", ")),
        Value::Object(m) => format!(
            "{{{}}}",
            m.iter()
                .map(|(k, e)| format!("{}: {}", str_lit(k), literal(e)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// JSON の値の Python のリテラル (複数行、キーは .avsc と同じ順)
fn pretty_literal(v: &Value, indent: usize, out: &mut String) {
    let pad = |n: usize| "    ".repeat(n);
    match v {
        Value::Array(a) if !a.is_empty() => {
            out.push_str("[\n");
            for e in a.iter() {
                out.push_str(&pad(indent + 1));
                pretty_literal(e, indent + 1, out);
                out.push_str(",\n");
            }
            out.push_str(&pad(indent));
            out.push(']');
        }
        Value::Object(m) if !m.is_empty() => {
            let mut keys: Vec<&String> = m.keys().collect();
            keys.sort_by_key(|k| key_rank(m, k));
            out.push_str("{\n");
            for k in keys.iter() {
                out.push_str(&pad(indent + 1));
                out.push_str(&str_lit(k));
                out.push_str(": ");
                pretty_literal(&m[k.as_str()], indent + 1, out);
                out.push_str(",\n");
            }
            out.push_str(&pad(indent));
            out.push('}');
        }
        other => out.push_str(&literal(other)),
    }
}

fn schema_literal(t: &DataType, indent: usize) -> Result<String, IdlError> {
    let schema = TypeSchema::from_data_type(t)
        .map_err(|e| generate_error(format!("{}: {e}", t.display_name())))?;
    let mut out = String::new();
    pretty_literal(&serde_json::to_value(schema).unwrap(), indent, &mut out);
    Ok(out)
}

/// 既定値を dataclass のフィールドに直接書けるなら、その Python のリテラル (None・真偽・数・文字列)
fn scalar_default(t: &DataType, default: &Value) -> Option<String> {
    let t = match t {
        DataType::Optional { inner, .. } => {
            if default.is_null() {
                return Some("None".to_owned());
            }
            inner.as_ref()
        }
        t => t,
    };
    match (t, default) {
        (DataType::Boolean, Value::Bool(_)) | (DataType::String, Value::String(_)) => {
            Some(literal(default))
        }
        (DataType::Int | DataType::Long, Value::Number(n)) if n.is_i64() => Some(n.to_string()),
        (DataType::Float | DataType::Double, Value::Number(n)) => {
            n.as_f64().map(|f| format!("{f:?}"))
        }
        _ => None,
    }
}

fn docstring(doc: &Option<String>, pad: &str) -> String {
    match doc {
        Some(d) => {
            let d = d.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
            let mut lines = d.lines();
            let mut out = format!("{pad}\"\"\"{}", lines.next().unwrap_or(""));
            let rest: Vec<&str> = lines.collect();
            if rest.is_empty() {
                out.push_str("\"\"\"\n");
            } else {
                out.push('\n');
                for l in rest {
                    if l.is_empty() {
                        out.push('\n');
                    } else {
                        out.push_str(&format!("{pad}{l}\n"));
                    }
                }
                out.push_str(&format!("{pad}\"\"\"\n"));
            }
            out
        }
        None => String::new(),
    }
}

fn record_code(t: &DataType, ns: &str, imports: &mut BTreeSet<String>) -> Result<String, IdlError> {
    let r = match t {
        DataType::Record(r) => r,
        _ => unreachable!(),
    };
    let name = type_ident(&r.name)?;
    let mut out = String::from("@_dataclasses.dataclass(kw_only=True)\n");
    out.push_str(&format!("class {name}:\n"));
    out.push_str(&docstring(&r.doc, "    "));
    if r.doc.is_some() {
        out.push('\n');
    }
    let mut fields = String::new();
    for f in r.fields.iter() {
        let attr = ident(&f.name, &METHODS);
        let ann = annotation(&f.data_type, ns, imports)?;
        if let Some(d) = &f.doc {
            for l in d.lines() {
                out.push_str(&format!(
                    "    #{}{l}\n",
                    if l.is_empty() { "" } else { " " }
                ));
            }
        }
        let default = f.default_as_dict();
        match &default {
            None => out.push_str(&format!("    {attr}: {ann}\n")),
            Some(d) => match scalar_default(&f.data_type, d) {
                Some(lit) => out.push_str(&format!("    {attr}: {ann} = {lit}\n")),
                None => out.push_str(&format!(
                    "    {attr}: {ann} = _dataclasses.field(default_factory=lambda: _jt.field_default({name}, {}))\n",
                    str_lit(&attr)
                )),
            },
        }
        fields.push_str(&format!(
            "        ({}, {}, {}, {}),\n",
            str_lit(&f.name),
            str_lit(&attr),
            converter(&f.data_type, ns, imports)?,
            match &default {
                None => "_jt.NO_DEFAULT".to_owned(),
                Some(d) => literal(d),
            }
        ));
    }
    if r.fields.is_empty() {
        out.push_str("    pass\n");
    }
    out.push_str(&format!(
        "
    def to_value(self) -> dict:
        \"\"\"辞書 (仕様 §4 の表し方) にする\"\"\"
        return _jt.record_to_value(self)

    @classmethod
    def from_value(cls, value, path: str = \"\") -> {name}:
        \"\"\"辞書を読む。足りないフィールドは既定値で埋め、型にないキーは無視する (仕様 §4)\"\"\"
        return _jt.record_from_value(cls, value, path)

    @classmethod
    def type_schema(cls) -> dict:
        \"\"\"型参照 {{name, fingerprint, avro}} (仕様 §6)\"\"\"
        return _jt.type_schema(cls)


_jt.define_record(
    {name},
    schema={},
    fields=lambda: [
{fields}    ],
)
",
        schema_literal(t, 1)?
    ));
    // 定数 (juiz.constants、仕様 §25) はクラス変数にする (dataclass のフィールドにしない)
    let constants =
        record_constants(r).map_err(|m| generate_error(format!("{}: {m}", r.full_name())))?;
    if !constants.is_empty() {
        out.push('\n');
        for c in constants.iter() {
            if let Some(d) = &c.doc {
                for l in d.lines() {
                    out.push_str(&format!("#{}{l}\n", if l.is_empty() { "" } else { " " }));
                }
            }
            out.push_str(&format!(
                "{name}.{} = {}\n",
                ident(&c.name, &METHODS),
                literal(&c.value)
            ));
        }
    }
    Ok(out)
}

fn enum_code(t: &DataType) -> Result<String, IdlError> {
    let e = match t {
        DataType::Enum(e) => e,
        _ => unreachable!(),
    };
    let name = type_ident(&e.name)?;
    let mut reserved: Vec<&str> = METHODS.to_vec();
    reserved.extend(ENUM_RESERVED);
    let mut out = format!("class {name}(_enum.Enum):\n");
    out.push_str(&docstring(&e.doc, "    "));
    if e.doc.is_some() {
        out.push('\n');
    }
    for s in e.symbols.iter() {
        out.push_str(&format!("    {} = {}\n", ident(s, &reserved), str_lit(s)));
    }
    out.push_str(&format!(
        "
    def to_value(self) -> str:
        \"\"\"記号の文字列にする\"\"\"
        return self.value

    @classmethod
    def from_value(cls, value, path: str = \"\") -> {name}:
        \"\"\"記号の文字列を読む。知らない記号は既定値があれば既定値にする (仕様 §4)\"\"\"
        return _jt.enum_from_value(cls, value, path)

    @classmethod
    def type_schema(cls) -> dict:
        \"\"\"型参照 {{name, fingerprint, avro}} (仕様 §6)\"\"\"
        return _jt.type_schema(cls)


_jt.define_enum(
    {name},
    schema={},
    default={},
)
",
        schema_literal(t, 1)?,
        e.default
            .as_deref()
            .map(str_lit)
            .unwrap_or_else(|| "None".to_owned())
    ));
    Ok(out)
}

/// `motor_state` → `MotorState`
fn camel_case(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn schema_type(schema: &TypeSchema) -> Result<DataType, IdlError> {
    schema
        .data_type()
        .map_err(|e| generate_error(format!("{}: {e}", schema.name)))
}

/// client stub の 1 つの呼び出しのメソッド (`def name(self, …) -> T:`)
fn call_method(
    method: &str,
    p: &ProcessSignature,
    proxy_expr: &str,
    ns: &str,
    imports: &mut BTreeSet<String>,
    pad: &str,
) -> Result<String, IdlError> {
    let mut params = vec!["self".to_owned()];
    let mut arguments = String::new();
    let mut seen_default = false;
    let mut star = false;
    for a in p.arguments.iter() {
        let t = schema_type(&a.schema)?;
        // 引数の self はメソッドの self とぶつかる
        let param = ident(&a.name, &["self"]);
        let ann = annotation(&t, ns, imports)?;
        match &a.default {
            Some(d) => {
                seen_default = true;
                // 既定値が辞書などで書けなければ渡さない (呼ばれる側の既定値を使う)
                let lit = scalar_default(&t, d).unwrap_or_else(|| "_jt.OMIT".to_owned());
                params.push(format!("{param}: {ann} = {lit}"));
            }
            None => {
                // 既定値のある引数より後ろの既定値のない引数は、キーワード引数にする (Python の決まり)
                if seen_default && !star {
                    params.push("*".to_owned());
                    star = true;
                }
                params.push(format!("{param}: {ann}"));
            }
        }
        arguments.push_str(&format!(
            "{pad}            ({}, {param}, {}),\n",
            str_lit(&a.name),
            converter(&t, ns, imports)?
        ));
    }
    let out_t = schema_type(&p.output_schema)?;
    let ret = annotation(&out_t, ns, imports)?;
    let mut out = format!("{pad}def {method}({}) -> {ret}:\n", params.join(", "));
    out.push_str(&docstring(&p.description, &format!("{pad}    ")));
    let arguments = if arguments.is_empty() {
        "[]".to_owned()
    } else {
        format!("[\n{arguments}{pad}        ]")
    };
    out.push_str(&format!(
        "{pad}    return _jt.typed_call(\n{pad}        {proxy_expr},\n{pad}        {arguments},\n{pad}        {},\n{pad}    )\n",
        converter(&out_t, ns, imports)?
    ));
    Ok(out)
}

fn process_client(
    p: &ProcessSignature,
    ns: &str,
    imports: &mut BTreeSet<String>,
) -> Result<String, IdlError> {
    let class = format!("{}Client", camel_case(&p.type_name));
    let mut out = format!("class {class}:\n");
    out.push_str(&format!(
        "    \"\"\"process {ns}.{} の型付きクライアント。proxy は juiz.proxy.ProcessProxy\"\"\"\n\n",
        p.type_name
    ));
    out.push_str(&format!("    type_name = {}\n\n", str_lit(&p.type_name)));
    out.push_str(
        "    def __init__(self, proxy):
        self.proxy = proxy

    @classmethod
    def connect(cls, name: str, host: str = \"localhost\", port: int = 8000, namespace: str | None = None):
        \"\"\"HTTP で juiz につなぎ、名前 (と ID ネームスペース) で Process を探す\"\"\"
        from juiz.proxy import ProcessProxy

        return cls(ProcessProxy(name, host, port, namespace=namespace))

",
    );
    out.push_str(&call_method(
        "__call__",
        p,
        "self.proxy",
        ns,
        imports,
        "    ",
    )?);
    Ok(out)
}

fn container_client(
    c: &ContainerSignature,
    ns: &str,
    imports: &mut BTreeSet<String>,
) -> Result<String, IdlError> {
    let class = format!("{}Client", camel_case(&c.type_name));
    let mut out = format!("class {class}:\n");
    let summary = format!(
        "container {ns}.{} の型付きクライアント。proxy は juiz.proxy.ContainerProxy",
        c.type_name
    );
    let doc = match &c.description {
        Some(d) => format!("{d}\n\n{summary}"),
        None => summary,
    };
    out.push_str(&docstring(&Some(doc), "    "));
    out.push('\n');
    out.push_str(&format!("    type_name = {}\n\n", str_lit(&c.type_name)));
    out.push_str(
        "    def __init__(self, proxy):
        self.proxy = proxy

    @classmethod
    def connect(cls, name: str, host: str = \"localhost\", port: int = 8000, namespace: str | None = None):
        \"\"\"HTTP で juiz につなぎ、名前 (と ID ネームスペース) で Container を探す\"\"\"
        from juiz.proxy import ContainerProxy

        return cls(ContainerProxy(name, host, port, namespace=namespace))
",
    );
    for p in c.container_processes.iter() {
        if KEYWORDS.contains(&p.type_name.as_str())
            || CLIENT_ATTRIBUTES.contains(&p.type_name.as_str())
            || p.type_name.starts_with('_')
        {
            return Err(generate_error(format!(
                "container_process '{}' of container '{}' cannot be a method name of the Python client",
                p.type_name, c.type_name
            )));
        }
        out.push('\n');
        out.push_str(&call_method(
            &p.type_name,
            p,
            &format!("getattr(self.proxy, {})", str_lit(&p.type_name)),
            ns,
            imports,
            "    ",
        )?);
    }
    Ok(out)
}

/// 1 つの名前空間のモジュール
fn module(
    ns: &str,
    types: &[&DataType],
    signatures: Option<&Signatures>,
) -> Result<String, IdlError> {
    let mut imports = BTreeSet::new();
    let mut body = String::new();
    let mut names: BTreeSet<String> = BTreeSet::new();
    for t in types.iter() {
        let (_, name) = named(t);
        names.insert(name.to_owned());
        body.push_str("\n\n");
        body.push_str(&match t {
            DataType::Record(_) => record_code(t, ns, &mut imports)?,
            DataType::Enum(_) => enum_code(t)?,
            _ => unreachable!(),
        });
    }
    if let Some(s) = signatures {
        let mut clients: Vec<(String, String)> = Vec::new();
        for p in s.processes.iter() {
            clients.push((p.type_name.clone(), process_client(p, ns, &mut imports)?));
        }
        for c in s.containers.iter() {
            clients.push((c.type_name.clone(), container_client(c, ns, &mut imports)?));
        }
        for (type_name, code) in clients {
            let class = format!("{}Client", camel_case(&type_name));
            if !names.insert(class.clone()) {
                return Err(generate_error(format!(
                    "Python client class '{class}' for '{type_name}' conflicts with another name in namespace '{ns}'"
                )));
            }
            body.push_str("\n\n");
            body.push_str(&code);
        }
    }
    let mut out = String::from(HEADER);
    out.push_str(&format!("\"\"\"juiz の型 {ns} (juiz-idl が生成)\"\"\"\n\n"));
    out.push_str("from __future__ import annotations\n\n");
    out.push_str(
        "import dataclasses as _dataclasses\nimport enum as _enum\nimport typing as _typing\n\n",
    );
    out.push_str("from juiz import datatype as _jt\n");
    if imports.contains(PIL_IMPORT) {
        out.push_str("import PIL.Image as _PILImage\n");
    }
    for i in imports.iter().filter(|i| i.as_str() != PIL_IMPORT) {
        out.push_str(&format!("import {i} as {}\n", namespace_alias(i)));
    }
    out.push_str(&body);
    Ok(out)
}

/// 名前付き型 (record・enum) と `process` / `container` 宣言の Python のコード
pub fn generate_python(
    types: &[DataType],
    signatures: &[Signatures],
) -> Result<Vec<GeneratedFile>, IdlError> {
    let mut by_namespace: BTreeMap<String, Vec<&DataType>> = BTreeMap::new();
    for t in types.iter() {
        let (namespace, _) = match t {
            DataType::Record(_) | DataType::Enum(_) => named(t),
            _ => continue,
        };
        if namespace.is_empty() {
            return Err(generate_error(format!(
                "type '{}' has no namespace; Python code needs a namespace for the package path",
                t.display_name()
            )));
        }
        by_namespace
            .entry(namespace.to_owned())
            .or_default()
            .push(t);
    }
    let mut sigs: BTreeMap<&str, &Signatures> = BTreeMap::new();
    for s in signatures
        .iter()
        .filter(|s| !s.processes.is_empty() || !s.containers.is_empty())
    {
        if s.namespace.is_empty() {
            return Err(generate_error(
                "process and container declarations need a namespace for Python code".to_owned(),
            ));
        }
        by_namespace.entry(s.namespace.clone()).or_default();
        sigs.insert(&s.namespace, s);
    }
    // 途中のパッケージ (a.b の a) も作る
    let mut packages: BTreeSet<String> = BTreeSet::new();
    for ns in by_namespace.keys() {
        let elements: Vec<&str> = ns.split('.').collect();
        for e in elements.iter() {
            type_ident(e)?;
        }
        for i in 1..=elements.len() {
            packages.insert(elements[..i].join("."));
        }
    }
    let mut files = Vec::new();
    for package in packages.iter() {
        let path = format!("{}/__init__.py", package.replace('.', "/"));
        let contents = match by_namespace.get(package) {
            Some(types) => module(package, types, sigs.get(package.as_str()).copied())?,
            None => {
                format!("{HEADER}\"\"\"juiz の型の名前空間 {package} (juiz-idl が生成)\"\"\"\n")
            }
        };
        files.push(GeneratedFile {
            path: path.into(),
            contents,
        });
    }
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identifiers() {
        assert_eq!(ident("from", &METHODS), "from_");
        assert_eq!(ident("to_value", &METHODS), "to_value_");
        assert_eq!(ident("type", &METHODS), "type");
        assert!(type_ident("None").is_err());
        assert!(type_ident("_jt").is_err());
        assert_eq!(camel_case("move_to"), "MoveTo");
    }

    #[test]
    fn literals() {
        assert_eq!(str_lit("a\"b\\\n"), "\"a\\\"b\\\\\\n\"");
        assert_eq!(
            literal(&serde_json::json!({"a": [true, null, 1.5, "x"]})),
            "{\"a\": [True, None, 1.5, \"x\"]}"
        );
        assert_eq!(
            scalar_default(&DataType::Double, &serde_json::json!(0)),
            Some("0.0".to_owned())
        );
        assert_eq!(
            scalar_default(&DataType::optional(DataType::Long), &serde_json::json!(3)),
            Some("3".to_owned())
        );
        assert_eq!(
            scalar_default(&DataType::Bytes, &serde_json::json!("AA==")),
            None
        );
    }
}
