//! `process` / `container` 宣言から Zig の雛形 (skeleton) を書き出す (仕様 §26.4、issue #576)
//!
//! 名前空間ごとに 1 つのファイル (`<名前空間の . を _ にしたもの>_component.zig`) を作る。中身は宣言ごとの関数
//! (本体は `return error.NotImplemented`) と、最後に zigjuiz の `juiz.exportComponent` で 1 つの Component にまとめる宣言。
//! record・enum の型は `juiz-idl -g zig` の juiz_idl.zig を `juiz_types` という名前で読み込んで使う
//! (zigjuiz の build.zig の `addTypes` が作るモジュール)。

use std::collections::BTreeMap;

use juiz_types::{DataType, TypeSchema};

use crate::rust_skeleton::camel_case;
use crate::zig::{any_literal, doc_lines, ident, string_literal, value_literal, zig_type, Scope};
use crate::{
    ContainerSignature, DesignSkeleton, GeneratedFile, IdlError, ProcessSignature, Signatures, StateInit,
};

/// 生成した型のモジュールを読み込む名前 (雛形の中で `types.robot.geometry.Pose2D` のように使う)
const TYPES: &str = "types";
/// 雛形のファイルが使う宣言の名前
const RESERVED: [&str; 3] = ["juiz", "types", "std"];

fn generate_error(message: String) -> IdlError {
    IdlError::Generate { message }
}

/// 雛形のファイルの名前 (名前空間 `my_robot.arm` → `my_robot_arm_component.zig`)
pub fn zig_skeleton_file(namespace: &str) -> String {
    format!("{}_component.zig", namespace.replace('.', "_"))
}

/// 名前空間ごとの雛形
pub fn generate_zig_skeleton(signatures: &[Signatures]) -> Result<Vec<GeneratedFile>, IdlError> {
    signatures
        .iter()
        .filter(|s| !s.processes.is_empty() || !s.containers.is_empty())
        .map(|s| {
            let doc = format!(
                "// @generated by juiz-idl.\n\
                 //! 名前空間 {ns} の process / container 宣言から作った Zig の雛形。コピーして関数の本体を書く。\n\
                 //! 型は juiz-idl -g zig の juiz_idl.zig を juiz_types という名前で読み込む (zigjuiz の build.zig の addTypes)。\n\
                 //! 1 つの名前空間が 1 つのコンポーネント (共有ライブラリ) になる。\n",
                ns = s.namespace
            );
            Ok(GeneratedFile {
                path: zig_skeleton_file(&s.namespace).into(),
                contents: zig_skeleton_items(s, &s.namespace.replace('.', "_"), &doc)?,
            })
        })
        .collect()
}

fn schema_type(schema: &TypeSchema) -> Result<DataType, IdlError> {
    schema
        .data_type()
        .map_err(|e| generate_error(format!("{}: {e}", schema.name)))
}

/// 引数の型 (zigjuiz が引数に受け取れる型)。受け取れない型はエラー
fn arg_type(t: &DataType, what: &str) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Image => "juiz.Image".to_owned(),
        DataType::Boolean
        | DataType::Int
        | DataType::Long
        | DataType::Float
        | DataType::Double
        | DataType::String
        | DataType::Record(_)
        | DataType::Enum(_) => zig_type(t, Scope::Index(TYPES))?,
        // 配列・辞書・any は型なしの juiz.Value で受け取る
        DataType::Array(_) | DataType::Map(_) | DataType::Any => "juiz.Value".to_owned(),
        DataType::Optional { .. } | DataType::Bytes | DataType::Null => {
            return Err(generate_error(format!(
                "{what}: {} cannot be an argument of a zigjuiz process (use a record that holds it)",
                t.display_name()
            )))
        }
    })
}

/// 戻り値の型
fn return_type(t: &DataType) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Null => "void".to_owned(),
        DataType::Image => "juiz.Image".to_owned(),
        DataType::Boolean
        | DataType::Int
        | DataType::Long
        | DataType::Float
        | DataType::Double
        | DataType::String
        | DataType::Record(_)
        | DataType::Enum(_) => zig_type(t, Scope::Index(TYPES))?,
        _ => "juiz.Value".to_owned(),
    })
}

/// 引数の struct のフィールド (既定値つき)
fn argument_field(a: &crate::ArgumentSignature, what: &str) -> Result<String, IdlError> {
    let t = schema_type(&a.schema)?;
    let what = format!("{what} argument '{}'", a.name);
    let ty = arg_type(&t, &what)?;
    let default = match (&t, a.default.as_ref()) {
        (_, None) | (DataType::Image, _) => None,
        (DataType::Array(_) | DataType::Map(_) | DataType::Any, Some(v)) => Some(any_literal(v)),
        (t, Some(v)) => Some(
            value_literal(t, v, Scope::Index(TYPES))
                .map_err(|e| generate_error(format!("{what}: {e}")))?,
        ),
    };
    Ok(match default {
        Some(d) => format!("{}: {ty} = {d}", ident(&a.name)),
        None => format!("{}: {ty}", ident(&a.name)),
    })
}

/// exportComponent の要素のオプション (.type_name・.description・.args)
fn part_options(p: &ProcessSignature, container: Option<&str>) -> String {
    let mut o = format!(".type_name = {}", string_literal(&p.type_name));
    if let Some(ct) = container {
        o.push_str(&format!(", .container_type = {}", string_literal(ct)));
    }
    if let Some(d) = &p.description {
        o.push_str(&format!(", .description = {}", string_literal(d)));
    }
    if !p.arguments.is_empty() {
        let docs = p
            .arguments
            .iter()
            .map(|a| {
                format!(
                    ".{} = {}",
                    ident(&a.name),
                    string_literal(a.description.as_deref().unwrap_or(""))
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        o.push_str(&format!(", .args = .{{ {docs} }}"));
    }
    o
}

struct Names {
    defined: BTreeMap<String, String>,
}

impl Names {
    fn define(&mut self, n: &str, what: String) -> Result<(), IdlError> {
        if RESERVED.contains(&n) {
            return Err(generate_error(format!(
                "{what} becomes the Zig name {n}, which the skeleton uses"
            )));
        }
        if let Some(other) = self.defined.insert(n.to_owned(), what.clone()) {
            return Err(generate_error(format!(
                "{other} and {what} both become the {}",
                if n.starts_with("type name ") {
                    n.to_owned()
                } else {
                    format!("Zig name {n}")
                }
            )));
        }
        Ok(())
    }
}

/// Container の状態の型の名前 (`arm` → `ArmState`)
fn state_name(container: &str) -> String {
    format!("{}State", camel_case(container))
}

fn create_name(container: &str) -> String {
    format!("{container}_create")
}

/// 関数 1 つ。`state` は ContainerProcess のときの状態の型
fn function_code(p: &ProcessSignature, state: Option<&str>) -> Result<String, IdlError> {
    let what = if state.is_some() {
        format!("container_process {}", p.type_name)
    } else {
        format!("process {}", p.type_name)
    };
    let mut params = Vec::new();
    let mut discard = Vec::new();
    if let Some(s) = state {
        params.push(format!("self: *{}", ident(s)));
        discard.push("self");
    }
    if !p.arguments.is_empty() {
        let fields = p
            .arguments
            .iter()
            .map(|a| argument_field(a, &what))
            .collect::<Result<Vec<_>, _>>()?;
        params.push(format!("args: struct {{ {} }}", fields.join(", ")));
        discard.push("args");
    }
    let ret = return_type(&schema_type(&p.output_schema)?)?;
    let mut out = doc_lines(&p.description, "");
    out.push_str(&format!(
        "fn {}({}) !{ret} {{\n",
        ident(&p.type_name),
        params.join(", ")
    ));
    for d in discard {
        out.push_str(&format!("    _ = {d};\n"));
    }
    out.push_str(&format!(
        "    // write the body of {}\n    return error.NotImplemented;\n}}\n",
        p.type_name
    ));
    Ok(out)
}

fn container_code(c: &ContainerSignature) -> Result<String, IdlError> {
    let state = state_name(&c.type_name);
    let mut out = format!(
        "/// State of the container {name} (the JIDL does not type it: add the fields you need)\n\
         pub const {s} = struct {{}};\n\n",
        name = c.type_name,
        s = ident(&state)
    );
    out.push_str(&doc_lines(&c.description, ""));
    out.push_str(&format!(
        "fn {}() {} {{\n    return .{{}};\n}}\n",
        ident(&create_name(&c.type_name)),
        ident(&state)
    ));
    for p in c.container_processes.iter() {
        out.push('\n');
        out.push_str(&function_code(p, Some(&state))?);
    }
    Ok(out)
}

/// 雛形のファイル全体。`doc` はファイルの先頭に置くコメント。
/// `juiz pkg create -b zig --idl` (Zig Step 5) がコンポーネントの名前を `component_name` にして使う
pub fn zig_skeleton_items(
    s: &Signatures,
    component_name: &str,
    doc: &str,
) -> Result<String, IdlError> {
    let mut names = Names {
        defined: BTreeMap::new(),
    };
    // exportComponent は同じ型名を 2 度使うとコンパイルエラーにするので、ここで先にエラーにする
    let mut type_names = Names {
        defined: BTreeMap::new(),
    };
    for p in s.processes.iter() {
        type_names.define(
            &format!("type name {}", p.type_name),
            format!("process {}", p.type_name),
        )?;
    }
    for c in s.containers.iter() {
        type_names.define(
            &format!("type name {}", c.type_name),
            format!("container {}", c.type_name),
        )?;
        for p in c.container_processes.iter() {
            type_names.define(
                &format!("type name {}", p.type_name),
                format!("container_process {}", p.type_name),
            )?;
        }
    }
    for p in s.processes.iter() {
        names.define(&p.type_name, format!("process {}", p.type_name))?;
    }
    for c in s.containers.iter() {
        names.define(
            &create_name(&c.type_name),
            format!("container {}", c.type_name),
        )?;
        names.define(
            &state_name(&c.type_name),
            format!("the state type of container {}", c.type_name),
        )?;
        for p in c.container_processes.iter() {
            names.define(&p.type_name, format!("container_process {}", p.type_name))?;
        }
    }

    let mut out = String::from(doc);
    out.push_str("const juiz = @import(\"juiz\");\nconst types = @import(\"juiz_types\");\n");
    let mut parts = Vec::new();
    for p in s.processes.iter() {
        out.push('\n');
        out.push_str(&function_code(p, None)?);
        parts.push(format!(
            "juiz.processPart({}, .{{ {} }})",
            ident(&p.type_name),
            part_options(p, None)
        ));
    }
    for c in s.containers.iter() {
        out.push('\n');
        out.push_str(&container_code(c)?);
        let mut o = format!(".type_name = {}", string_literal(&c.type_name));
        if let Some(d) = &c.description {
            o.push_str(&format!(", .description = {}", string_literal(d)));
        }
        parts.push(format!(
            "juiz.containerPart({}, .{{ {o} }})",
            ident(&create_name(&c.type_name))
        ));
        for p in c.container_processes.iter() {
            parts.push(format!(
                "juiz.containerProcessPart({}, .{{ {} }})",
                ident(&p.type_name),
                part_options(p, Some(&c.type_name))
            ));
        }
    }
    out.push_str(&format!(
        "\ncomptime {{\n    juiz.exportComponent(.{{\n        .type_name = {},\n        .parts = .{{\n",
        string_literal(component_name)
    ));
    for part in parts.iter() {
        out.push_str(&format!("            {part},\n"));
    }
    out.push_str("        },\n    });\n}\n");
    Ok(out)
}

