/// 生成したファイルが使う宣言の名前。型・名前空間の名前と重なってはならない
const RESERVED_DECLS: [&str; 2] = ["juiz", "std"];

/// struct / enum の中に生成する宣言。フィールド・記号・定数と重なってはならない
const RESERVED_MEMBERS: [&str; 2] = ["juiz_type", "juiz_default"];

fn generate_error(message: String) -> IdlError {
    IdlError::Generate { message }
}

fn named(t: &DataType) -> (&str, &str) {
    match t {
        DataType::Record(r) => (&r.namespace, &r.name),
        DataType::Enum(e) => (&e.namespace, &e.name),
        _ => unreachable!(),
    }
}

fn full_name(t: &DataType) -> String {
    let (ns, name) = named(t);
    format!("{ns}.{name}")
}

/// `iN` / `uN` (任意の幅の整数型) か
fn is_int_type_name(s: &str) -> bool {
    let mut c = s.chars();
    matches!(c.next(), Some('i' | 'u'))
        && !c.as_str().is_empty()
        && c.as_str().chars().all(|d| d.is_ascii_digit())
}

/// Zig の識別子。キーワード・組み込みの名前・識別子にならない名前は `@"..."` で包む
pub(crate) fn ident(name: &str) -> String {
    let plain = name.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if plain && !KEYWORDS.contains(&name) && !PRIMITIVES.contains(&name) && !is_int_type_name(name)
    {
        name.to_owned()
    } else {
        format!("@{}", string_literal(name))
    }
}

/// 列挙の記号を Zig の enum のフィールド名 (snake_case の小文字) にする (`Idle` → `idle`、`HighSpeed` → `high_speed`)
pub(crate) fn enum_field(symbol: &str) -> String {
    let mut out = String::new();
    let mut prev: Option<char> = None;
    for c in symbol.chars() {
        if c.is_ascii_uppercase() {
            if matches!(prev, Some(p) if p.is_ascii_lowercase() || p.is_ascii_digit()) {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
        prev = Some(c);
    }
    out
}

/// 名前空間 `a.b` のファイル `a/b.zig`
pub(crate) fn file_path(ns: &str) -> String {
    format!("{}.zig", ns.replace('.', "/"))
}

/// ファイル `from_ns` から名前空間 `to_ns` のファイルへの相対パス
fn relative_path(from_ns: &str, to_ns: &str) -> String {
    let depth = from_ns.split('.').count() - 1;
    format!("{}{}", "../".repeat(depth), file_path(to_ns))
}

/// Zig の文字列リテラル。`"`・`\`・制御文字はエスケープする。Zig のソースは UTF-8 と決まっているので、ASCII 以外の文字はそのまま書く
pub(crate) fn string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                out.push_str(&format!("\\x{:02x}", c as u32))
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// バイト列のリテラル (`bytes` の既定値)。ASCII の表示できる文字以外は `\x..` にする
fn bytes_literal(bytes: &[u8]) -> String {
    let mut out = String::from("\"");
    for &b in bytes {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b' '..=b'~' => out.push(b as char),
            _ => out.push_str(&format!("\\x{b:02x}")),
        }
    }
    out.push('"');
    out
}

/// 型の名前の書き方。`Local(ns)` は名前空間 ns のファイルの中 (ほかの名前空間の型は `@"a.b".T`)、
/// `Index(root)` は juiz_idl.zig を root という名前で読み込んだファイルの中 (雛形、`root.a.b.T`)
#[derive(Clone, Copy)]
pub(crate) enum Scope<'a> {
    Local(&'a str),
    Index(&'a str),
}

fn named_type_path(t: &DataType, scope: Scope) -> String {
    let (ns, name) = named(t);
    match scope {
        Scope::Local(here) if here == ns => ident(name),
        Scope::Local(_) => format!("@{}.{}", string_literal(ns), ident(name)),
        Scope::Index(root) => {
            let mut s = root.to_owned();
            for e in ns.split('.') {
                s.push('.');
                s.push_str(&ident(e));
            }
            s.push('.');
            s.push_str(&ident(name));
            s
        }
    }
}

/// 型の Zig の表記
pub(crate) fn zig_type(t: &DataType, scope: Scope) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Null => {
            return Err(generate_error(
                "null cannot be a field type in Zig".to_owned(),
            ))
        }
        DataType::Boolean => "bool".to_owned(),
        DataType::Int => "i32".to_owned(),
        DataType::Long => "i64".to_owned(),
        DataType::Float => "f32".to_owned(),
        DataType::Double => "f64".to_owned(),
        DataType::String => "[]const u8".to_owned(),
        DataType::Bytes => "juiz.Bytes".to_owned(),
        DataType::Array(items) => format!("[]const {}", zig_type(items, scope)?),
        DataType::Map(values) => format!("juiz.Map({})", zig_type(values, scope)?),
        DataType::Optional { inner, .. } => format!("?{}", zig_type(inner, scope)?),
        DataType::Record(_) | DataType::Enum(_) => named_type_path(t, scope),
        DataType::Any => "juiz.Value".to_owned(),
        DataType::Image => {
            return Err(generate_error(
                "image cannot be used inside a record (spec §3.3)".to_owned(),
            ))
        }
    })
}

fn float_literal(f: f64) -> String {
    // {:?} は 1.0 のように必ず小数点か指数を付ける
    format!("{f:?}")
}

fn number_literal(n: &serde_json::Number, float: bool) -> String {
    if float {
        float_literal(n.as_f64().unwrap_or(0.0))
    } else {
        n.to_string()
    }
}

/// 辞書の値 (仕様 §4) を `juiz.Value` の値にする式
pub(crate) fn any_literal(v: &Value) -> String {
    match v {
        Value::Null => ".null".to_owned(),
        Value::Bool(b) => format!(".{{ .bool = {b} }}"),
        Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                format!(".{{ .int = {i} }}")
            } else if let Some(u) = n.as_u64() {
                format!(".{{ .uint = {u} }}")
            } else {
                format!(
                    ".{{ .float = {} }}",
                    float_literal(n.as_f64().unwrap_or(0.0))
                )
            }
        }
        Value::String(s) => format!(".{{ .string = {} }}", string_literal(s)),
        Value::Array(a) => format!(
            ".{{ .array = {} }}",
            list(a.iter().map(any_literal).collect())
        ),
        Value::Object(m) => format!(
            ".{{ .object = {} }}",
            list(
                m.iter()
                    .map(|(k, e)| format!(
                        ".{{ .key = {}, .value = {} }}",
                        string_literal(k),
                        any_literal(e)
                    ))
                    .collect()
            )
        ),
    }
}

/// スライスのリテラル `&.{ a, b }` (空なら `&.{}`)
fn list(items: Vec<String>) -> String {
    if items.is_empty() {
        "&.{}".to_owned()
    } else if items.len() == 1 && items[0].starts_with(".{") {
        // zig fmt と同じ書き方 (要素が 1 つの struct なら括弧の内側に空白を入れない)
        format!("&.{{{}}}", items[0])
    } else {
        format!("&.{{ {} }}", items.join(", "))
    }
}

fn mismatch(t: &DataType, v: &Value) -> IdlError {
    generate_error(format!(
        "default value {v} does not match {}",
        t.display_name()
    ))
}

/// 型 t の値 v (辞書での表し方、仕様 §4) を Zig の式にする (フィールドの既定値・雛形の引数の既定値)
pub(crate) fn value_literal(t: &DataType, v: &Value, scope: Scope) -> Result<String, IdlError> {
    Ok(match (t, v) {
        (DataType::Optional { .. }, Value::Null) => "null".to_owned(),
        (DataType::Optional { inner, .. }, v) => value_literal(inner, v, scope)?,
        (DataType::Boolean, Value::Bool(b)) => b.to_string(),
        (DataType::Int | DataType::Long, Value::Number(n)) if n.is_i64() => {
            number_literal(n, false)
        }
        (DataType::Float | DataType::Double, Value::Number(n)) => number_literal(n, true),
        (DataType::String, Value::String(s)) => string_literal(s),
        (DataType::Bytes, Value::String(s)) => {
            use base64::Engine;
            let bytes = base64::engine::general_purpose::STANDARD
                .decode(s)
                .map_err(|_| mismatch(t, v))?;
            format!(".{{ .data = {} }}", bytes_literal(&bytes))
        }
        (DataType::Array(items), Value::Array(a)) => list(
            a.iter()
                .map(|e| value_literal(items, e, scope))
                .collect::<Result<Vec<_>, _>>()?,
        ),
        (DataType::Map(values), Value::Object(m)) => format!(
            ".{{ .entries = {} }}",
            list(
                m.iter()
                    .map(|(k, e)| Ok(format!(
                        ".{{ .key = {}, .value = {} }}",
                        string_literal(k),
                        value_literal(values, e, scope)?
                    )))
                    .collect::<Result<Vec<_>, IdlError>>()?
            )
        ),
        (DataType::Record(r), Value::Object(m)) => {
            let mut parts = Vec::new();
            for f in r.fields.iter() {
                if let Some(e) = m.get(&f.name) {
                    parts.push(format!(
                        ".{} = {}",
                        ident(&f.name),
                        value_literal(&f.data_type, e, scope)?
                    ));
                }
            }
            if parts.is_empty() {
                ".{}".to_owned()
            } else {
                format!(".{{ {} }}", parts.join(", "))
            }
        }
        (DataType::Enum(e), Value::String(s)) if e.symbols.contains(s) => {
            format!(".{}", ident(&enum_field(s)))
        }
        (DataType::Any, v) => any_literal(v),
        _ => return Err(mismatch(t, v)),
    })
}

/// `///` の説明
pub(crate) fn doc_lines(doc: &Option<String>, pad: &str) -> String {
    match doc {
        Some(d) => d
            .lines()
            .map(|l| {
                if l.is_empty() {
                    format!("{pad}///\n")
                } else {
                    format!("{pad}/// {l}\n")
                }
            })
            .collect(),
        None => String::new(),
    }
}

/// 型が参照する名前付き型の名前空間
fn collect_ref_namespaces(t: &DataType, out: &mut Vec<String>) {
    match t {
        DataType::Array(i) | DataType::Map(i) => collect_ref_namespaces(i, out),
        DataType::Optional { inner, .. } => collect_ref_namespaces(inner, out),
        DataType::Record(_) | DataType::Enum(_) => out.push(named(t).0.to_owned()),
        _ => {}
    }
}

/// 名前付き型 (record・enum) の Zig のファイル。名前空間ごとに 1 つと、全部を読み込む juiz_idl.zig
pub fn generate_zig(types: &[DataType]) -> Result<Vec<GeneratedFile>, IdlError> {
    let mut by_namespace: BTreeMap<String, Vec<&DataType>> = BTreeMap::new();
    for t in types.iter() {
        if matches!(t, DataType::Record(_) | DataType::Enum(_)) {
            let (ns, _) = named(t);
            if ns.is_empty() {
                return Err(generate_error(format!(
                    "type '{}' has no namespace; Zig code needs a namespace",
                    t.display_name()
                )));
            }
            by_namespace.entry(ns.to_owned()).or_default().push(t);
        }
    }
    // 名前空間の木 (juiz_idl.zig と、子の名前空間を持つファイルの `pub const 子 = @import(...)`)
    let mut children: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut nodes: Vec<String> = Vec::new();
    for ns in by_namespace.keys() {
        for e in ns.split('.') {
            if RESERVED_DECLS.contains(&e) {
                return Err(generate_error(format!(
                    "namespace '{ns}': the element '{e}' is used by the generated Zig code"
                )));
            }
        }
        let parts: Vec<&str> = ns.split('.').collect();
        for i in 0..parts.len() {
            let node = parts[..=i].join(".");
            if !nodes.contains(&node) {
                nodes.push(node.clone());
                let parent = parts[..i].join(".");
                children
                    .entry(parent)
                    .or_default()
                    .push(parts[i].to_owned());
            }
        }
    }

    let mut files = Vec::new();
    for (ns, ts) in by_namespace.iter() {
        let kids = children.get(ns).cloned().unwrap_or_default();
        files.push(GeneratedFile {
            path: file_path(ns).into(),
            contents: file_code(ns, ts, &kids)?,
        });
    }
    files.push(GeneratedFile {
        path: INDEX_FILE.into(),
        contents: index_code(&by_namespace, &children),
    });
    Ok(files)
}

fn index_code(
    by_namespace: &BTreeMap<String, Vec<&DataType>>,
    children: &BTreeMap<String, Vec<String>>,
) -> String {
    fn node(
        out: &mut String,
        prefix: &str,
        name: &str,
        pad: &str,
        by_namespace: &BTreeMap<String, Vec<&DataType>>,
        children: &BTreeMap<String, Vec<String>>,
    ) {
        let ns = if prefix.is_empty() {
            name.to_owned()
        } else {
            format!("{prefix}.{name}")
        };
        if by_namespace.contains_key(&ns) {
            // ファイルのある名前空間は、子の名前空間をファイルの中で読み込んでいる
            out.push_str(&format!(
                "{pad}pub const {} = @import({});\n",
                ident(name),
                string_literal(&file_path(&ns))
            ));
        } else {
            out.push_str(&format!("{pad}pub const {} = struct {{\n", ident(name)));
            for c in children.get(&ns).into_iter().flatten() {
                node(out, &ns, c, &format!("{pad}    "), by_namespace, children);
            }
            out.push_str(&format!("{pad}}};\n"));
        }
    }
    let mut out = String::from(HEADER);
    out.push_str("//! juiz-idl -g zig で作った全部の名前空間 (juiz のデータ型、docs/spec/datatype.md §26)。\n");
    out.push_str("//! zigjuiz の build.zig の addTypes はこのファイルをモジュールの根にする。\n");
    for c in children.get("").into_iter().flatten() {
        node(&mut out, "", c, "", by_namespace, children);
    }
    out
}

/// struct / enum の中の名前が重ならないことを確かめる
fn add_member(
    members: &mut BTreeMap<String, String>,
    name: &str,
    owner: &str,
) -> Result<(), IdlError> {
    if RESERVED_MEMBERS.contains(&name) {
        return Err(generate_error(format!(
            "{owner} becomes the Zig name '{name}', which the generated code uses"
        )));
    }
    if let Some(prev) = members.insert(name.to_owned(), owner.to_owned()) {
        return Err(generate_error(format!(
            "{prev} and {owner} both become the Zig name '{name}'"
        )));
    }
    Ok(())
}

fn file_code(ns: &str, ts: &[&DataType], kids: &[String]) -> Result<String, IdlError> {
    // ファイルの中の名前 (型と、子の名前空間)
    let mut decls: BTreeMap<String, String> = BTreeMap::new();
    for t in ts.iter() {
        let name = named(t).1;
        if RESERVED_DECLS.contains(&name) {
            return Err(generate_error(format!(
                "type {}: the name '{name}' is used by the generated Zig code",
                full_name(t)
            )));
        }
        add_member(&mut decls, name, &format!("type {}", full_name(t)))?;
    }
    for k in kids.iter() {
        add_member(&mut decls, k, &format!("namespace {ns}.{k}"))?;
    }

    let scope = Scope::Local(ns);
    let mut imports: Vec<String> = Vec::new();
    let mut body = String::new();
    for t in ts.iter() {
        let full = full_name(t);
        let tn = ident(named(t).1);
        body.push('\n');
        match t {
            DataType::Record(r) => {
                let mut members = BTreeMap::new();
                body.push_str(&doc_lines(&r.doc, ""));
                body.push_str(&format!("pub const {tn} = struct {{\n"));
                for f in r.fields.iter() {
                    add_member(&mut members, &f.name, &format!("field {full}.{}", f.name))?;
                    let mut refs = Vec::new();
                    collect_ref_namespaces(&f.data_type, &mut refs);
                    for r in refs {
                        if r != ns && !imports.contains(&r) {
                            imports.push(r);
                        }
                    }
                    body.push_str(&doc_lines(&f.doc, "    "));
                    let ty = zig_type(&f.data_type, scope)?;
                    match f.default_as_dict() {
                        Some(d) => body.push_str(&format!(
                            "    {}: {ty} = {},\n",
                            ident(&f.name),
                            value_literal(&f.data_type, &d, scope)
                                .map_err(|e| generate_error(format!("{full}.{}: {e}", f.name)))?
                        )),
                        None => body.push_str(&format!("    {}: {ty},\n", ident(&f.name))),
                    }
                }
                // 定数 (juiz.constants、仕様 §25) は struct の中の pub const にする
                let constants =
                    record_constants(r).map_err(|m| generate_error(format!("{full}: {m}")))?;
                for c in constants.iter() {
                    add_member(
                        &mut members,
                        &c.name,
                        &format!("constant {full}.{}", c.name),
                    )?;
                    let (ty, lit) = match (&c.data_type, &c.value) {
                        (DataType::String, Value::String(s)) => ("[]const u8", string_literal(s)),
                        (t, v) => (
                            match t {
                                DataType::Boolean => "bool",
                                DataType::Int => "i32",
                                DataType::Long => "i64",
                                DataType::Float => "f32",
                                _ => "f64",
                            },
                            value_literal(t, v, scope)?,
                        ),
                    };
                    body.push('\n');
                    body.push_str(&doc_lines(&c.doc, "    "));
                    body.push_str(&format!(
                        "    pub const {}: {ty} = {lit};\n",
                        ident(&c.name)
                    ));
                }
                body.push('\n');
                body.push_str(&type_info_code(t, None)?);
                body.push_str("};\n");
            }
            DataType::Enum(e) => {
                let mut members = BTreeMap::new();
                body.push_str(&doc_lines(&e.doc, ""));
                body.push_str(&format!("pub const {tn} = enum {{\n"));
                for s in e.symbols.iter() {
                    let f = enum_field(s);
                    add_member(&mut members, &f, &format!("symbol {full}.{s}"))?;
                    body.push_str(&format!("    {},\n", ident(&f)));
                }
                if let Some(d) = &e.default {
                    body.push_str(&format!(
                        "\n    /// 列挙の既定値 (知らない記号を読んだときの値、仕様 §4)\n    pub const juiz_default: {tn} = .{};\n",
                        ident(&enum_field(d))
                    ));
                }
                body.push('\n');
                body.push_str(&type_info_code(t, Some(&e.symbols))?);
                body.push_str("};\n");
            }
            _ => unreachable!(),
        }
    }

    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "//! 名前空間 {ns} の型 (juiz のデータ型、docs/spec/datatype.md §26)\n"
    ));
    out.push_str("const juiz = @import(\"juiz\");\n");
    imports.sort();
    for i in imports.iter() {
        out.push_str(&format!(
            "const @{} = @import({});\n",
            string_literal(i),
            string_literal(&relative_path(ns, i))
        ));
    }
    for k in kids.iter() {
        out.push_str(&format!(
            "/// 子の名前空間 {ns}.{k}\npub const {} = @import({});\n",
            ident(k),
            string_literal(&relative_path(ns, &format!("{ns}.{k}")))
        ));
    }
    out.push_str(&body);
    Ok(out)
}

fn type_info_code(t: &DataType, symbols: Option<&[String]>) -> Result<String, IdlError> {
    let avro = t.to_avro().map_err(|e| IdlError::Generate {
        message: format!("{}: {e}", t.display_name()),
    })?;
    let avro = serde_json::to_string(&avro).unwrap();
    let mut s = format!(
        "    /// 型の情報 (.avsc と同じスキーマ。zigjuiz が libjuiz_sdk に渡す)\n    pub const juiz_type: juiz.TypeInfo = .{{\n        .name = {},\n        .fingerprint = {},\n        .avro = {},\n",
        string_literal(&full_name(t)),
        string_literal(&t.fingerprint()),
        string_literal(&avro)
    );
    if let Some(symbols) = symbols {
        s.push_str(&format!(
            "        .symbols = &.{{ {} }},\n",
            symbols
                .iter()
                .map(|x| string_literal(x))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    s.push_str("    };\n");
    Ok(s)
}

