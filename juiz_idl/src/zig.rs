//! Zig のコードの書き出し (仕様 §11・§26、issue #576)
//!
//! 名前空間 `a.b` ごとにファイル `a/b.zig` を作り、record を素の `struct`、enum を `enum` にして、
//! 型の情報 (Avro のスキーマと指紋) を持つ `pub const juiz_type: juiz.TypeInfo` 宣言を足す。
//! 辞書との変換は zigjuiz が `@typeInfo` で汎用に行うので、生成するのは型の定義だけ。
//! 全部の名前空間を読み込む `juiz_idl.zig` も書く (zigjuiz の build.zig の `addTypes` はこれをモジュールの根にする)。
//!
//! 型参照は .avsc と同じスキーマを埋め込む。zigjuiz は libjuiz_sdk (Rust の juiz_types) に指紋を計算させて
//! マニフェストに載せるので、指紋は .avsc・Rust・Python・C++・Haskell と一致する。埋め込んだ `fingerprint` は
//! 生成したときの値で、表示や検査に使う。

