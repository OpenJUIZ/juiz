//! `process` / `container` 宣言から Haskell の雛形 (skeleton) を書き出す (仕様 §22.4、issue #468)
//!
//! 名前空間ごとに 1 つのモジュール (`<CamelCase の名前空間>Component.hs`) を作る。中身は hsjuiz の
//! マニフェストと関数 (本体は `error`) の組を宣言ごとに持ち、最後に `juizComponent` で Component にする。
//! record・enum の型は `juiz-idl -g haskell` のモジュールを `import qualified` して使う。

use std::collections::{BTreeMap, BTreeSet};

use juiz_types::{DataType, TypeSchema};
use serde_json::Value;

use crate::haskell::{
    atom, doc_lines, hs_type, lower_first, module_name, string_literal, value_literal,
};
use crate::rust_skeleton::camel_case;
use crate::{ContainerSignature, GeneratedFile, IdlError, ProcessSignature, Signatures};

fn generate_error(message: String) -> IdlError {
    IdlError::Generate { message }
}

/// 雛形のモジュールの名前 (名前空間 `my_robot.arm` → `MyRobotArmComponent`)
pub fn haskell_skeleton_module(namespace: &str) -> String {
    let base: String = namespace.split('.').map(camel_case).collect();
    format!("{base}Component")
}

/// 名前空間ごとの雛形
pub fn generate_haskell_skeleton(
    signatures: &[Signatures],
) -> Result<Vec<GeneratedFile>, IdlError> {
    signatures
        .iter()
        .filter(|s| !s.processes.is_empty() || !s.containers.is_empty())
        .map(|s| {
            let module = haskell_skeleton_module(&s.namespace);
            let doc = format!(
                "-- @generated by juiz-idl.\n\
                 -- 名前空間 {ns} の process / container 宣言から作った Haskell の雛形。コピーして error の本体を書く。\n\
                 -- 型は juiz-idl -g haskell のモジュールを使う (cabal の hs-source-dirs に出力先を足し、other-modules に書く)。\n\
                 -- 1 つの名前空間が 1 つのコンポーネント (foreign-library) になる。\n",
                ns = s.namespace
            );
            Ok(GeneratedFile {
                path: format!("{module}.hs").into(),
                contents: haskell_skeleton_items(s, &s.namespace.replace('.', "_"), &module, &doc)?,
            })
        })
        .collect()
}

fn schema_type(schema: &TypeSchema) -> Result<DataType, IdlError> {
    schema
        .data_type()
        .map_err(|e| generate_error(format!("{}: {e}", schema.name)))
}

/// 引数・戻り値の Haskell の型 (record の中に書けない image・null もここでは書ける)
fn arg_type(t: &DataType) -> Result<String, IdlError> {
    match t {
        DataType::Image => Ok("Image".to_owned()),
        DataType::Null => Ok("()".to_owned()),
        t => hs_type(t, ""),
    }
}

/// 負の数は括弧で包む
fn number(s: String) -> String {
    if s.starts_with('-') {
        format!("({s})")
    } else {
        s
    }
}

/// マニフェストに足す行
fn argument_line(a: &crate::ArgumentSignature) -> Result<String, IdlError> {
    let t = schema_type(&a.schema)?;
    let name = string_literal(&a.name);
    let desc = string_literal(a.description.as_deref().unwrap_or(""));
    let d = a.default.as_ref();
    Ok(match (&t, d) {
        (DataType::Record(_) | DataType::Enum(_), None) => {
            format!("addTypedArgNoDefault (Proxy :: Proxy {}) {name} {desc}", arg_type(&t)?)
        }
        (DataType::Record(_) | DataType::Enum(_), Some(v)) => format!(
            "addTypedArgValue (Proxy :: Proxy {}) {name} {desc} ({})",
            arg_type(&t)?,
            value_literal(v)
        ),
        (DataType::Image, _) => format!("addImageArg {name} {desc}"),
        (DataType::Boolean, Some(Value::Bool(b))) => {
            format!("addBoolArg {name} {desc} {}", if *b { "True" } else { "False" })
        }
        (DataType::Int | DataType::Long, Some(Value::Number(n))) if n.is_i64() => {
            format!("addIntArg {name} {desc} {}", number(n.to_string()))
        }
        (DataType::Float | DataType::Double, Some(Value::Number(n))) => format!(
            "addFloatArg {name} {desc} {}",
            number(format!("{:?}", n.as_f64().unwrap_or(0.0)))
        ),
        (DataType::String, Some(Value::String(s))) => {
            format!("addStringArg {name} {desc} {}", string_literal(s))
        }
        // そのほか (既定値なしは JNull)
        (_, d) => format!(
            "addArg {} {name} {desc} ({})",
            string_literal(&a.type_name),
            value_literal(d.unwrap_or(&Value::Null))
        ),
    })
}

/// 関数の引数の変数名 (使わないので `_` で始める)
fn var(name: &str) -> String {
    format!("_{name}")
}

struct Names {
    defined: BTreeMap<String, String>,
}

impl Names {
    fn define(&mut self, n: &str, what: String) -> Result<(), IdlError> {
        if let Some(other) = self.defined.insert(n.to_owned(), what.clone()) {
            return Err(generate_error(format!(
                "{other} and {what} both become the Haskell name {n}"
            )));
        }
        Ok(())
    }
}

fn fn_name(type_name: &str, suffix: &str) -> String {
    format!("{}_{suffix}", lower_first(type_name))
}

/// Container の状態の型の名前 (`arm` → `ArmState`)
fn state_name(container: &str) -> String {
    format!("{}State", camel_case(container))
}

/// マニフェストと関数。`container` は (状態の型, Container の型名)
fn process_code(p: &ProcessSignature, container: Option<(&str, &str)>) -> Result<String, IdlError> {
    let manifest = fn_name(&p.type_name, "manifest");
    let func = fn_name(&p.type_name, "process");
    let mut out = doc_lines(&p.description, "", '|');
    out.push_str(&format!("{manifest} :: ProcessManifest\n{manifest} = "));
    match container {
        Some((_, ct)) => out.push_str(&format!(
            "containerProcessManifest {} {}",
            string_literal(&p.type_name),
            string_literal(ct)
        )),
        None => out.push_str(&format!("processManifest {}", string_literal(&p.type_name))),
    }
    if let Some(d) = &p.description {
        out.push_str(&format!("\n  & description {}", string_literal(d)));
    }
    for a in p.arguments.iter() {
        out.push_str(&format!("\n  & {}", argument_line(a)?));
    }
    out.push_str("\n\n");
    let mut types = Vec::new();
    let mut vars = Vec::new();
    if let Some((state, _)) = container {
        types.push(state.to_owned());
        let mut first = var("container");
        while p.arguments.iter().any(|a| var(&a.name) == first) {
            first.push('_');
        }
        vars.push(first);
    }
    for a in p.arguments.iter() {
        types.push(arg_type(&schema_type(&a.schema)?)?);
        vars.push(var(&a.name));
    }
    let ret = arg_type(&schema_type(&p.output_schema)?)?;
    // ContainerProcess は状態 (IORef など) を読み書きするので IO にする
    let ret = if container.is_some() {
        format!("IO {}", atom(ret))
    } else {
        ret
    };
    types.push(ret);
    out.push_str(&format!("{func} :: {}\n", types.join(" -> ")));
    let mut head = func.clone();
    for v in vars.iter() {
        head.push(' ');
        head.push_str(v);
    }
    out.push_str(&format!(
        "{head} = error {}\n",
        string_literal(&format!("write the body of {}", p.type_name))
    ));
    Ok(out)
}

fn container_code(c: &ContainerSignature) -> Result<String, IdlError> {
    let state = state_name(&c.type_name);
    let manifest = fn_name(&c.type_name, "manifest");
    let create = fn_name(&c.type_name, "create");
    let mut out = format!(
        "-- | State of the container {name} (the JIDL does not type it: add the fields you need,\n\
         -- an IORef for a value that changes)\n\
         data {state} = {state}\n\n",
        name = c.type_name
    );
    out.push_str(&doc_lines(&c.description, "", '|'));
    out.push_str(&format!(
        "{manifest} :: ContainerManifest\n{manifest} = containerManifest {}",
        string_literal(&c.type_name)
    ));
    if let Some(d) = &c.description {
        out.push_str(&format!("\n  & description {}", string_literal(d)));
    }
    out.push_str(&format!("\n\n{create} :: IO {state}\n{create} = pure {state}\n"));
    for p in c.container_processes.iter() {
        out.push('\n');
        out.push_str(&process_code(p, Some((&state, &c.type_name)))?);
    }
    Ok(out)
}

fn collect_modules(t: &DataType, out: &mut BTreeSet<String>) -> Result<(), IdlError> {
    match t {
        DataType::Array(i) | DataType::Map(i) => collect_modules(i, out),
        DataType::Optional { inner, .. } => collect_modules(inner, out),
        DataType::Record(r) => {
            out.insert(module_name(&r.namespace)?);
            Ok(())
        }
        DataType::Enum(e) => {
            out.insert(module_name(&e.namespace)?);
            Ok(())
        }
        _ => Ok(()),
    }
}

/// 雛形のモジュール全体。`doc` はファイルの先頭 (プラグマの後、module の前) に置くコメント。
/// `juiz pkg create --idl` (docs/spec/pkg.md §6.5) がコンポーネントの名前を `component_name`、
/// モジュール名を `<Name>` にして src/<Name>.hs に使う
pub fn haskell_skeleton_items(
    s: &Signatures,
    component_name: &str,
    module: &str,
    doc: &str,
) -> Result<String, IdlError> {
    let mut names = Names {
        defined: BTreeMap::new(),
    };
    let component = format!("{}_component", lower_first(component_name));
    names.define(&component, "the Component manifest".to_owned())?;
    let mut modules = BTreeSet::new();
    for p in s.processes.iter() {
        names.define(&fn_name(&p.type_name, "manifest"), format!("process {}", p.type_name))?;
        names.define(&fn_name(&p.type_name, "process"), format!("process {}", p.type_name))?;
    }
    for c in s.containers.iter() {
        names.define(&fn_name(&c.type_name, "manifest"), format!("container {}", c.type_name))?;
        names.define(&fn_name(&c.type_name, "create"), format!("container {}", c.type_name))?;
        names.define(&state_name(&c.type_name), format!("the state type of container {}", c.type_name))?;
        for p in c.container_processes.iter() {
            names.define(&fn_name(&p.type_name, "manifest"), format!("container_process {}", p.type_name))?;
            names.define(&fn_name(&p.type_name, "process"), format!("container_process {}", p.type_name))?;
        }
    }
    let all = s
        .processes
        .iter()
        .chain(s.containers.iter().flat_map(|c| c.container_processes.iter()));
    for p in all {
        for schema in p.arguments.iter().map(|a| &a.schema).chain([&p.output_schema]) {
            collect_modules(&schema_type(schema)?, &mut modules)?;
        }
    }

    let mut out = String::from(
        "{-# LANGUAGE OverloadedStrings #-}\n{-# LANGUAGE TemplateHaskell #-}\n{-# OPTIONS_GHC -Wno-unused-imports #-}\n",
    );
    out.push_str(doc);
    out.push_str(&format!("module {module} () where\n\n"));
    out.push_str(
        "import qualified Data.ByteString as HB\n\
         import qualified Data.Int as HI\n\
         import qualified Data.Map.Strict as HM\n\
         import qualified Data.Text as HT\n\
         import Juiz\n\
         import qualified Juiz.Value as JV\n",
    );
    for m in modules.iter() {
        out.push_str(&format!("import qualified {m}\n"));
    }
    out.push_str(&format!(
        "\n-- | The manifest of the whole Component (the types in this plugin)\n{component} :: ComponentManifest\n{component} = componentManifest {}\n",
        string_literal(component_name)
    ));
    let mut entries = Vec::new();
    for p in s.processes.iter() {
        out.push('\n');
        out.push_str(&process_code(p, None)?);
        entries.push(format!(
            "componentProcess '{} '{}",
            fn_name(&p.type_name, "process"),
            fn_name(&p.type_name, "manifest")
        ));
    }
    for c in s.containers.iter() {
        out.push('\n');
        out.push_str(&container_code(c)?);
        entries.push(format!(
            "componentContainer '{} '{}",
            fn_name(&c.type_name, "create"),
            fn_name(&c.type_name, "manifest")
        ));
        for p in c.container_processes.iter() {
            entries.push(format!(
                "componentContainerProcess '{} '{}",
                fn_name(&p.type_name, "process"),
                fn_name(&p.type_name, "manifest")
            ));
        }
    }
    out.push_str(&format!("\njuizComponent '{component}\n"));
    for (i, e) in entries.iter().enumerate() {
        out.push_str(&format!("  {} {e}\n", if i == 0 { "[" } else { "," }));
    }
    out.push_str("  ]\n");
    Ok(out)
}

