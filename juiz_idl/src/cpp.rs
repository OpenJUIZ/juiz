//! C++ のコードの書き出し (仕様 §11・§21、issue #195)
//!
//! 名前空間 `a.b` ごとにヘッダ `a.b.h` を作り、record を struct、enum を `enum class` にして、
//! cppjuiz の `juiz::type_traits<T>` (辞書との変換・型参照・ネイティブ値の codec) を特殊化する。
//! 全部の名前空間を読み込むヘッダ `juiz_idl.h` も作る。ヘッダだけで使え、cppjuiz の `juiz/types.h` に依存する。
//!
//! 型参照は .avsc と同じスキーマを埋め込み、libjuiz_sdk (Rust の juiz_types) が指紋を計算するので、
//! 指紋は .avsc・Rust・Python の生成コードと一致する。

