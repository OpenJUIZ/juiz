fn generate_error(message: String) -> IdlError {
    IdlError::Generate { message }
}

/// フィールド名・記号を C++ の識別子にする。キーワードは末尾に `_` を付ける
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

/// 型の名前・名前空間の要素。キーワードは使えない
fn type_ident(name: &str) -> Result<String, IdlError> {
    if KEYWORDS.contains(&name) {
        return Err(generate_error(format!(
            "'{name}' cannot be used as a C++ type or namespace name"
        )));
    }
    Ok(name.to_owned())
}

fn named(t: &DataType) -> (&str, &str) {
    match t {
        DataType::Record(r) => (&r.namespace, &r.name),
        DataType::Enum(e) => (&e.namespace, &e.name),
        _ => unreachable!(),
    }
}

fn full_name(t: &DataType) -> String {
    let (ns, name) = named(t);
    format!("{ns}.{name}")
}

/// 名前付き型の C++ の完全修飾名 (`::a::b::T`)
fn named_path(t: &DataType) -> Result<String, IdlError> {
    let (ns, name) = named(t);
    let mut out = String::new();
    for e in ns.split('.') {
        out.push_str("::");
        out.push_str(&type_ident(e)?);
    }
    out.push_str("::");
    out.push_str(&type_ident(name)?);
    Ok(out)
}

fn cpp_type(t: &DataType) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Null => {
            return Err(generate_error(
                "null cannot be a field type in C++".to_owned(),
            ))
        }
        DataType::Boolean => "bool".to_owned(),
        DataType::Int => "int32_t".to_owned(),
        DataType::Long => "int64_t".to_owned(),
        DataType::Float => "float".to_owned(),
        DataType::Double => "double".to_owned(),
        DataType::String => "std::string".to_owned(),
        DataType::Bytes => "std::vector<uint8_t>".to_owned(),
        DataType::Array(items) => format!("std::vector<{}>", cpp_type(items)?),
        DataType::Map(values) => format!("std::map<std::string, {}>", cpp_type(values)?),
        DataType::Optional { inner, .. } => format!("std::optional<{}>", cpp_type(inner)?),
        DataType::Record(_) | DataType::Enum(_) => named_path(t)?,
        DataType::Any => "juiz::Value".to_owned(),
        DataType::Image => {
            return Err(generate_error(
                "image cannot be used inside a record (spec §3.3)".to_owned(),
            ))
        }
    })
}

/// 型が参照する名前付き型の完全名 (入れ子の record の中には入らない)
fn collect_refs(t: &DataType, out: &mut BTreeSet<String>) {
    match t {
        DataType::Array(i) | DataType::Map(i) => collect_refs(i, out),
        DataType::Optional { inner, .. } => collect_refs(inner, out),
        DataType::Record(_) | DataType::Enum(_) => {
            out.insert(full_name(t));
        }
        _ => {}
    }
}

fn dependencies(t: &DataType) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    if let DataType::Record(r) = t {
        for f in r.fields.iter() {
            collect_refs(&f.data_type, &mut out);
        }
    }
    out
}

/// C++ の文字列リテラル。`"`・`\`・制御文字・ASCII 以外のバイトはエスケープする (ソースの文字コードに依らないように)
fn string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'?' => out.push_str("\\?"),
            0x20..=0x7e => out.push(b as char),
            _ => out.push_str(&format!("\\{b:03o}")),
        }
    }
    out.push('"');
    out
}

/// 長い文字列は、隣り合う文字列リテラルに分けて書く (MSVC は 1 つのリテラルの長さに上限がある)
fn long_string_literal(s: &str, pad: &str) -> String {
    let mut parts = Vec::new();
    let mut current = String::new();
    for c in s.chars() {
        current.push(c);
        if current.len() >= 200 {
            parts.push(string_literal(&current));
            current.clear();
        }
    }
    if !current.is_empty() || parts.is_empty() {
        parts.push(string_literal(&current));
    }
    parts.join(&format!("\n{pad}"))
}

fn double_literal(f: f64) -> String {
    let s = format!("{f:?}");
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

/// 辞書の値 (仕様 §4) を juiz::Value を作る式にする
fn value_literal(v: &Value) -> String {
    match v {
        Value::Null => "juiz::Value()".to_owned(),
        Value::Bool(b) => format!("juiz::Value({b})"),
        Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                format!("juiz::Value({})", long_literal(i))
            } else {
                format!("juiz::Value({})", double_literal(n.as_f64().unwrap_or(0.0)))
            }
        }
        Value::String(s) => format!("juiz::Value(std::string({}))", string_literal(s)),
        Value::Array(a) => format!(
            "juiz::Value(std::vector<juiz::Value>{{{}}})",
            a.iter().map(value_literal).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(m) => format!(
            "juiz::Value(std::map<std::string, juiz::Value>{{{}}})",
            m.iter()
                .map(|(k, e)| format!("{{{}, {}}}", string_literal(k), value_literal(e)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn long_literal(i: i64) -> String {
    if i == i64::MIN {
        "(-INT64_C(9223372036854775807) - 1)".to_owned()
    } else {
        format!("INT64_C({i})")
    }
}

/// フィールドの既定値の初期化子 (`{}` の中身)。基本型と列挙はリテラル、それ以外は辞書から作る
fn default_initializer(t: &DataType, dict: &Value) -> Result<String, IdlError> {
    Ok(match (t, dict) {
        (DataType::Boolean, Value::Bool(b)) => format!("{b}"),
        (DataType::Int, Value::Number(n)) if n.is_i64() => {
            format!("int32_t({})", n.as_i64().unwrap())
        }
        (DataType::Long, Value::Number(n)) if n.is_i64() => long_literal(n.as_i64().unwrap()),
        (DataType::Float, Value::Number(n)) => {
            format!("{}f", double_literal(n.as_f64().unwrap_or(0.0)))
        }
        (DataType::Double, Value::Number(n)) => double_literal(n.as_f64().unwrap_or(0.0)),
        (DataType::String, Value::String(s)) => string_literal(s),
        (DataType::Enum(_), Value::String(s)) => format!("{}::{}", named_path(t)?, ident(s)),
        (DataType::Optional { .. }, Value::Null) => "std::nullopt".to_owned(),
        (DataType::Optional { inner, .. }, v)
            if matches!(
                inner.as_ref(),
                DataType::Boolean
                    | DataType::Int
                    | DataType::Long
                    | DataType::Float
                    | DataType::Double
                    | DataType::String
                    | DataType::Enum(_)
            ) =>
        {
            format!("{}({})", cpp_type(t)?, default_initializer(inner, v)?)
        }
        _ => format!(
            "juiz::type_traits<{}>::from_value({})",
            cpp_type(t)?,
            value_literal(dict)
        ),
    })
}

fn doc_lines(doc: &Option<String>, pad: &str) -> String {
    match doc {
        Some(d) => d
            .lines()
            .map(|l| format!("{pad}//{}{l}\n", if l.is_empty() { "" } else { " " }))
            .collect(),
        None => String::new(),
    }
}

/// 名前付き型 (record・enum) の C++ のヘッダ。名前空間ごとのファイルと `juiz_idl.h`
pub fn generate_cpp(types: &[DataType]) -> Result<Vec<GeneratedFile>, IdlError> {
    let mut by_name: HashMap<String, &DataType> = HashMap::new();
    for t in types.iter() {
        match t {
            DataType::Record(_) | DataType::Enum(_) => {
                let (ns, _) = named(t);
                if ns.is_empty() {
                    return Err(generate_error(format!(
                        "type '{}' has no namespace; C++ code needs a namespace",
                        t.display_name()
                    )));
                }
                by_name.insert(full_name(t), t);
            }
            _ => {}
        }
    }
    // 参照する型が先に来るように並べる (record は値で持つので、使う前に定義が要る)
    let mut ordered: Vec<&DataType> = Vec::new();
    let mut done: BTreeSet<String> = BTreeSet::new();
    fn visit<'a>(
        name: &str,
        by_name: &HashMap<String, &'a DataType>,
        done: &mut BTreeSet<String>,
        visiting: &mut BTreeSet<String>,
        ordered: &mut Vec<&'a DataType>,
    ) -> Result<(), IdlError> {
        if done.contains(name) {
            return Ok(());
        }
        let Some(t) = by_name.get(name) else {
            return Ok(());
        };
        if !visiting.insert(name.to_owned()) {
            return Err(generate_error(format!("type '{name}' refers to itself")));
        }
        for d in dependencies(t).iter() {
            visit(d, by_name, done, visiting, ordered)?;
        }
        visiting.remove(name);
        done.insert(name.to_owned());
        ordered.push(t);
        Ok(())
    }
    for t in types.iter() {
        if matches!(t, DataType::Record(_) | DataType::Enum(_)) {
            visit(
                &full_name(t),
                &by_name,
                &mut done,
                &mut BTreeSet::new(),
                &mut ordered,
            )?;
        }
    }

    let mut by_namespace: BTreeMap<String, Vec<&DataType>> = BTreeMap::new();
    let mut ns_deps: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for t in ordered.iter() {
        let ns = named(t).0.to_owned();
        for d in dependencies(t).iter() {
            if let Some(dt) = by_name.get(d) {
                let dns = named(dt).0;
                if dns != ns {
                    ns_deps
                        .entry(ns.clone())
                        .or_default()
                        .insert(dns.to_owned());
                }
            }
        }
        by_namespace.entry(ns).or_default().push(t);
    }
    // 名前空間のヘッダは参照する名前空間のヘッダを読み込むので、名前空間どうしの循環は書けない
    for (ns, deps) in ns_deps.iter() {
        let mut stack: Vec<String> = deps.iter().cloned().collect();
        let mut seen = BTreeSet::new();
        while let Some(d) = stack.pop() {
            if &d == ns {
                return Err(generate_error(format!(
                    "namespace '{ns}' and the namespaces it refers to refer to each other; C++ headers cannot include each other"
                )));
            }
            if seen.insert(d.clone()) {
                if let Some(dd) = ns_deps.get(&d) {
                    stack.extend(dd.iter().cloned());
                }
            }
        }
    }

    let mut files = Vec::new();
    for (ns, ts) in by_namespace.iter() {
        let mut out = String::from(HEADER);
        out.push_str("#pragma once\n\n");
        out.push_str("#include <cstdint>\n#include <map>\n#include <optional>\n#include <string>\n#include <vector>\n\n");
        out.push_str("#include <juiz/types.h>\n");
        for d in ns_deps.get(ns).into_iter().flatten() {
            out.push_str(&format!("#include \"{d}.h\"\n"));
        }
        for t in ts.iter() {
            out.push('\n');
            out.push_str(&type_code(t)?);
        }
        files.push(GeneratedFile {
            path: format!("{ns}.h").into(),
            contents: out,
        });
    }
    let mut all = String::from(HEADER);
    all.push_str("#pragma once\n\n");
    for ns in by_namespace.keys() {
        all.push_str(&format!("#include \"{ns}.h\"\n"));
    }
    files.push(GeneratedFile {
        path: CPP_ALL_HEADER.into(),
        contents: all,
    });
    Ok(files)
}

fn namespace_open(ns: &str) -> Result<String, IdlError> {
    let parts = ns
        .split('.')
        .map(type_ident)
        .collect::<Result<Vec<_>, _>>()?;
    Ok(format!("namespace {} {{\n", parts.join("::")))
}

fn type_info_fn(t: &DataType) -> Result<String, IdlError> {
    let avro = t.to_avro().map_err(|e| IdlError::Generate {
        message: format!("{}: {e}", t.display_name()),
    })?;
    let avro = serde_json::to_string(&avro).unwrap();
    Ok(format!(
        "    static const TypeInfo& type_info() {{
        return local_type_info<{}>(
            {});
    }}
    // ABI タグ (メモリ上の形の版) に入れる、生成器の版
    static std::string layout() {{ return \"juiz-idl-{}\"; }}
",
        named_path(t)?,
        long_string_literal(&avro, "            "),
        env!("CARGO_PKG_VERSION")
    ))
}

fn type_code(t: &DataType) -> Result<String, IdlError> {
    let path = named_path(t)?;
    let (ns, _) = named(t);
    let mut out = String::new();
    match t {
        DataType::Record(r) => {
            let name = type_ident(&r.name)?;
            out.push_str(&namespace_open(ns)?);
            out.push_str(&doc_lines(&r.doc, ""));
            out.push_str(&format!("struct {name} {{\n"));
            let mut eqs = Vec::new();
            let mut to_values = String::new();
            let mut from_values = String::new();
            for f in r.fields.iter() {
                let fident = ident(&f.name);
                let ty = cpp_type(&f.data_type)?;
                let init = match f.default_as_dict() {
                    Some(d) => default_initializer(&f.data_type, &d)?,
                    None => String::new(),
                };
                out.push_str(&doc_lines(&f.doc, "    "));
                out.push_str(&format!("    {ty} {fident}{{{init}}};\n"));
                eqs.push(format!("{fident} == o.{fident}"));
                to_values.push_str(&format!(
                    "        m.emplace({}, type_traits<{ty}>::to_value(v.{fident}));\n",
                    string_literal(&f.name)
                ));
                from_values.push_str(&format!(
                    "        if (auto it = o.find({}); it != o.end()) out.{fident} = type_traits<{ty}>::from_value(it->second);\n",
                    string_literal(&f.name)
                ));
            }
            let eq = if eqs.is_empty() {
                "true".to_owned()
            } else {
                eqs.join(" && ")
            };
            out.push_str(&format!(
                "\n    bool operator==(const {name}& o) const {{ return {eq}; }}\n    bool operator!=(const {name}& o) const {{ return !(*this == o); }}\n"
            ));
            out.push_str("};\n}\n\n");
            out.push_str("namespace juiz {\n");
            out.push_str(&format!("template<> struct type_traits<{path}> {{\n"));
            out.push_str("    // Process の戻り値になったとき、辞書にせず C++ の値のまま渡す (遅延評価 L3)\n");
            out.push_str("    static constexpr bool native = true;\n");
            out.push_str(&type_info_fn(t)?);
            out.push_str(&format!(
                "    static juiz::Value to_value(const {path}& v) {{
        std::map<std::string, juiz::Value> m;
{to_values}        return juiz::Value(std::move(m));
    }}
    // v は型で読んだ後の値 (足りないフィールドは既定値で埋めてある、仕様 §4)
    static {path} from_value(const juiz::Value& v) {{
        {path} out;
        if (!v.isObjectValue()) return out;
        const auto& o = v.objectValue();
{from_values}        return out;
    }}
}};
}}
"
            ));
        }
        DataType::Enum(e) => {
            let name = type_ident(&e.name)?;
            out.push_str(&namespace_open(ns)?);
            out.push_str(&doc_lines(&e.doc, ""));
            out.push_str(&format!("enum class {name} {{\n"));
            let mut to_values = String::new();
            let mut from_values = String::new();
            for s in e.symbols.iter() {
                let v = ident(s);
                out.push_str(&format!("    {v},\n"));
                to_values.push_str(&format!(
                    "        case {path}::{v}: return juiz::Value(std::string({}));\n",
                    string_literal(s)
                ));
                from_values.push_str(&format!(
                    "        if (s == {}) return {path}::{v};\n",
                    string_literal(s)
                ));
            }
            out.push_str("};\n}\n\n");
            let fallback = ident(e.default.as_ref().unwrap_or(&e.symbols[0]));
            out.push_str("namespace juiz {\n");
            out.push_str(&format!("template<> struct type_traits<{path}> {{\n"));
            out.push_str("    static constexpr bool native = false;\n");
            out.push_str(&type_info_fn(t)?);
            out.push_str(&format!(
                "    static juiz::Value to_value(const {path}& v) {{
        switch (v) {{
{to_values}        }}
        return juiz::Value();
    }}
    // 知らない記号は既定値 (仕様 §4。型で読んだ後なので普通は来ない)
    static {path} from_value(const juiz::Value& v) {{
        const std::string s = v.isStringValue() ? v.stringValue() : std::string();
{from_values}        return {path}::{fallback};
    }}
}};
}}
"
            ));
        }
        _ => unreachable!(),
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn literals() {
        assert_eq!(string_literal("a\"b\\c"), "\"a\\\"b\\\\c\"");
        assert_eq!(string_literal("あ"), "\"\\343\\201\\202\"");
        assert_eq!(double_literal(1.0), "1.0");
        assert_eq!(
            long_literal(i64::MIN),
            "(-INT64_C(9223372036854775807) - 1)"
        );
        assert_eq!(
            value_literal(&serde_json::json!({"a": [1, 1.5, null]})),
            "juiz::Value(std::map<std::string, juiz::Value>{{\"a\", juiz::Value(std::vector<juiz::Value>{juiz::Value(INT64_C(1)), juiz::Value(1.5), juiz::Value()})}})"
        );
    }

    #[test]
    fn keywords() {
        assert_eq!(ident("class"), "class_");
        assert!(type_ident("namespace").is_err());
    }
}
