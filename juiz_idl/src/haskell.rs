//! Haskell のコードの書き出し (仕様 §11・§22、issue #196)
//!
//! 名前空間 `a.b` ごとにモジュール `A.B` (ファイル `A/B.hs`) を作り、record を record 構文の data、
//! enum を直和型にして、hsjuiz の `JuizType` / `FromCapsule` / `ToCapsule` のインスタンスを書く。
//! Template Haskell は使わない (生成したモジュールはふつうの Haskell のソース)。hsjuiz に依存する。
//!
//! 型参照は .avsc と同じスキーマを埋め込み、libjuiz_sdk (Rust の juiz_types) が指紋を計算するので、
//! 指紋は .avsc・Rust・Python・C++ の生成コードと一致する。

use std::collections::{BTreeMap, BTreeSet};

use juiz_types::DataType;
use serde_json::Value;

use crate::constants::record_constants;
use crate::{GeneratedFile, IdlError};

const HEADER: &str =
    "-- @generated by juiz-idl. 手で直さないこと (元の .jidl / .avsc を直して作り直す)\n";

/// 生成したコードが Prelude から使う名前。生成する型・構築子・関数の名前はこれと重ならないようにする
const RESERVED: [&str; 14] = [
    "Eq", "Ord", "Show", "Enum", "Bounded", "Maybe", "Just", "Nothing", "Either", "Left", "Right",
    "pure", "TypeInfo", "Value",
];

fn generate_error(message: String) -> IdlError {
    IdlError::Generate { message }
}

fn named(t: &DataType) -> (&str, &str) {
    match t {
        DataType::Record(r) => (&r.namespace, &r.name),
        DataType::Enum(e) => (&e.namespace, &e.name),
        _ => unreachable!(),
    }
}

fn full_name(t: &DataType) -> String {
    let (ns, name) = named(t);
    format!("{ns}.{name}")
}

fn upper_first(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

fn lower_first(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_ascii_lowercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

/// 型名・名前空間の要素を Haskell の大文字で始まる名前にする。英字で始まらなければエラー
fn upper_ident(name: &str, what: &str) -> Result<String, IdlError> {
    if !name.starts_with(|c: char| c.is_ascii_alphabetic()) {
        return Err(generate_error(format!(
            "{what} '{name}' must start with a letter to be used in Haskell"
        )));
    }
    Ok(upper_first(name))
}

/// 名前空間 `a.b` のモジュール名 `A.B`
fn module_name(ns: &str) -> Result<String, IdlError> {
    Ok(ns
        .split('.')
        .map(|e| upper_ident(e, "namespace element"))
        .collect::<Result<Vec<_>, _>>()?
        .join("."))
}

fn type_name(t: &DataType) -> Result<String, IdlError> {
    upper_ident(named(t).1, "type name")
}

/// フィールド名を、型名の後ろに付ける部分にする (`frame_id` → `FrameId`)
fn camel(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(upper_first)
        .collect()
}

/// フィールドの関数名 (`Pose2D` の `frame_id` → `pose2DFrameId`)
fn accessor(type_name: &str, field: &str) -> String {
    let suffix = camel(field);
    let suffix = if suffix.is_empty() {
        // `_` だけの名前
        "Field".to_owned()
    } else {
        suffix
    };
    format!("{}{suffix}", lower_first(type_name))
}

/// 列挙の構築子 (`MotorMode` の `Idle` → `MotorModeIdle`)
fn constructor(type_name: &str, symbol: &str) -> String {
    format!("{type_name}{}", upper_first(symbol))
}

/// 型の Haskell の表記。`ns` は今書いているモジュールの名前空間 (ほかの名前空間の型は修飾する)
fn hs_type(t: &DataType, ns: &str) -> Result<String, IdlError> {
    Ok(match t {
        DataType::Null => {
            return Err(generate_error(
                "null cannot be a field type in Haskell".to_owned(),
            ))
        }
        DataType::Boolean => "Bool".to_owned(),
        DataType::Int => "HI.Int32".to_owned(),
        DataType::Long => "HI.Int64".to_owned(),
        DataType::Float => "Float".to_owned(),
        DataType::Double => "Double".to_owned(),
        DataType::String => "HT.Text".to_owned(),
        DataType::Bytes => "HB.ByteString".to_owned(),
        DataType::Array(items) => format!("[{}]", hs_type(items, ns)?),
        DataType::Map(values) => format!("HM.Map HT.Text {}", atom(hs_type(values, ns)?)),
        DataType::Optional { inner, .. } => format!("Maybe {}", atom(hs_type(inner, ns)?)),
        DataType::Record(_) | DataType::Enum(_) => {
            let (tns, _) = named(t);
            if tns == ns {
                type_name(t)?
            } else {
                format!("{}.{}", module_name(tns)?, type_name(t)?)
            }
        }
        DataType::Any => "JV.Value".to_owned(),
        DataType::Image => {
            return Err(generate_error(
                "image cannot be used inside a record (spec §3.3)".to_owned(),
            ))
        }
    })
}

/// 型の適用の引数にするときは括弧で包む
fn atom(s: String) -> String {
    if s.contains(' ') && !s.starts_with('[') {
        format!("({s})")
    } else {
        s
    }
}

/// 型が参照する名前付き型 (入れ子の record の中には入らない)
fn collect_refs<'a>(t: &'a DataType, out: &mut Vec<&'a DataType>) {
    match t {
        DataType::Array(i) | DataType::Map(i) => collect_refs(i, out),
        DataType::Optional { inner, .. } => collect_refs(inner, out),
        DataType::Record(_) | DataType::Enum(_) => out.push(t),
        _ => {}
    }
}

/// Haskell の文字列リテラル。`"`・`\`・制御文字・ASCII 以外の文字はエスケープする
fn string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            ' '..='~' => out.push(c),
            _ => out.push_str(&format!("\\{}\\&", c as u32)),
        }
    }
    out.push('"');
    out
}

fn number_literal(n: &serde_json::Number) -> String {
    if let Some(i) = n.as_i64() {
        let s = format!("JV.JInt {i}");
        if i < 0 {
            format!("JV.JInt ({i})")
        } else {
            s
        }
    } else if let Some(u) = n.as_u64() {
        format!("JV.JUInt {u}")
    } else {
        let f = n.as_f64().unwrap_or(0.0);
        let s = format!("{f:?}");
        if f < 0.0 {
            format!("JV.JFloat ({s})")
        } else {
            format!("JV.JFloat {s}")
        }
    }
}

/// 辞書の値 (仕様 §4) を hsjuiz の `Value` を作る式にする
fn value_literal(v: &Value) -> String {
    match v {
        Value::Null => "JV.JNull".to_owned(),
        Value::Bool(b) => format!("JV.JBool {}", if *b { "True" } else { "False" }),
        Value::Number(n) => number_literal(n),
        Value::String(s) => format!("JV.JString {}", string_literal(s)),
        Value::Array(a) => format!(
            "JV.JArray [{}]",
            a.iter().map(value_literal).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(m) => format!(
            "JV.JObject (HM.fromList [{}])",
            m.iter()
                .map(|(k, e)| format!("({}, {})", string_literal(k), value_literal(e)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// Haddock のコメント。`mark` は `|` (次の宣言の説明) か `^` (前のフィールドの説明)
fn doc_lines(doc: &Option<String>, pad: &str, mark: char) -> String {
    match doc {
        Some(d) => {
            let mut out = String::new();
            for (i, l) in d.lines().enumerate() {
                let head = if i == 0 {
                    format!("-- {mark}")
                } else {
                    "--".to_owned()
                };
                out.push_str(&format!(
                    "{pad}{head}{}{l}\n",
                    if l.is_empty() { "" } else { " " }
                ));
            }
            out
        }
        None => String::new(),
    }
}

/// 名前付き型 (record・enum) の Haskell のモジュール。名前空間ごとに 1 つ
pub fn generate_haskell(types: &[DataType]) -> Result<Vec<GeneratedFile>, IdlError> {
    let mut by_namespace: BTreeMap<String, Vec<&DataType>> = BTreeMap::new();
    for t in types.iter() {
        if matches!(t, DataType::Record(_) | DataType::Enum(_)) {
            let (ns, _) = named(t);
            if ns.is_empty() {
                return Err(generate_error(format!(
                    "type '{}' has no namespace; Haskell code needs a namespace",
                    t.display_name()
                )));
            }
            by_namespace.entry(ns.to_owned()).or_default().push(t);
        }
    }
    // モジュールどうしの import (Haskell のモジュールは hs-boot なしでは互いに import できない)
    let mut ns_deps: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for (ns, ts) in by_namespace.iter() {
        for t in ts.iter() {
            if let DataType::Record(r) = t {
                let mut refs = Vec::new();
                for f in r.fields.iter() {
                    collect_refs(&f.data_type, &mut refs);
                }
                for d in refs.iter() {
                    let dns = named(d).0;
                    if dns != ns {
                        ns_deps
                            .entry(ns.clone())
                            .or_default()
                            .insert(dns.to_owned());
                    }
                }
            }
        }
    }
    for (ns, deps) in ns_deps.iter() {
        let mut stack: Vec<String> = deps.iter().cloned().collect();
        let mut seen = BTreeSet::new();
        while let Some(d) = stack.pop() {
            if &d == ns {
                return Err(generate_error(format!(
                    "namespace '{ns}' and the namespaces it refers to refer to each other; Haskell modules cannot import each other"
                )));
            }
            if seen.insert(d.clone()) {
                if let Some(dd) = ns_deps.get(&d) {
                    stack.extend(dd.iter().cloned());
                }
            }
        }
    }

    let mut files = Vec::new();
    let mut modules = BTreeMap::new();
    for (ns, ts) in by_namespace.iter() {
        let module = module_name(ns)?;
        if let Some(other) = modules.insert(module.clone(), ns.clone()) {
            return Err(generate_error(format!(
                "namespaces '{other}' and '{ns}' both become the Haskell module {module}"
            )));
        }
        files.push(GeneratedFile {
            path: format!("{}.hs", module.replace('.', "/")).into(),
            contents: module_code(ns, &module, ts, ns_deps.get(ns))?,
        });
    }
    Ok(files)
}

/// モジュールの中で名前が重ならないことを確かめる
struct Names {
    types: BTreeMap<String, String>,
    values: BTreeMap<String, String>,
}

impl Names {
    fn add(map: &mut BTreeMap<String, String>, name: &str, owner: &str) -> Result<(), IdlError> {
        if RESERVED.contains(&name) {
            return Err(generate_error(format!(
                "{owner} becomes the Haskell name '{name}', which the generated code uses"
            )));
        }
        if let Some(prev) = map.insert(name.to_owned(), owner.to_owned()) {
            return Err(generate_error(format!(
                "{prev} and {owner} both become the Haskell name '{name}'"
            )));
        }
        Ok(())
    }
    fn add_type(&mut self, name: &str, owner: &str) -> Result<(), IdlError> {
        Self::add(&mut self.types, name, owner)
    }
    fn add_value(&mut self, name: &str, owner: &str) -> Result<(), IdlError> {
        Self::add(&mut self.values, name, owner)
    }
}

fn module_code(
    ns: &str,
    module: &str,
    ts: &[&DataType],
    deps: Option<&BTreeSet<String>>,
) -> Result<String, IdlError> {
    let mut names = Names {
        types: BTreeMap::new(),
        values: BTreeMap::new(),
    };
    let mut exports = Vec::new();
    let mut body = String::new();
    for t in ts.iter() {
        let tn = type_name(t)?;
        let full = full_name(t);
        names.add_type(&tn, &format!("type {full}"))?;
        exports.push(format!("{tn} (..)"));
        let info = format!("typeInfo{tn}");
        names.add_value(&info, &format!("the type information of {full}"))?;
        body.push('\n');
        match t {
            DataType::Record(r) => {
                // record の構築子は型と同じ名前 (構築子の名前空間)
                let fields = r
                    .fields
                    .iter()
                    .map(|f| {
                        let acc = accessor(&tn, &f.name);
                        names.add_value(&acc, &format!("field {full}.{}", f.name))?;
                        Ok((f, acc, hs_type(&f.data_type, ns)?))
                    })
                    .collect::<Result<Vec<_>, IdlError>>()?;
                let all_default = r.fields.iter().all(|f| f.default.is_some());
                let default_name = format!("default{tn}");
                if all_default {
                    names.add_value(&default_name, &format!("the default value of {full}"))?;
                    exports.push(default_name.clone());
                }
                body.push_str(&doc_lines(&r.doc, "", '|'));
                if fields.is_empty() {
                    body.push_str(&format!("data {tn} = {tn}\n  deriving (Eq, Show)\n"));
                } else {
                    body.push_str(&format!("data {tn} = {tn}\n"));
                    for (i, (f, acc, ty)) in fields.iter().enumerate() {
                        let lead = if i == 0 { "  { " } else { "  , " };
                        body.push_str(&format!("{lead}{acc} :: {ty}\n"));
                        body.push_str(&doc_lines(&f.doc, "    ", '^'));
                    }
                    body.push_str("  }\n  deriving (Eq, Show)\n");
                }
                body.push_str(&type_info_code(t, &tn, &info)?);
                let reads = if fields.is_empty() {
                    format!("\\_ -> pure {tn}")
                } else {
                    let mut s = format!("\\o -> {tn}");
                    for (i, (f, _, _)) in fields.iter().enumerate() {
                        let def = match f.default_as_dict() {
                            Some(d) => format!("(Just ({}))", value_literal(&d)),
                            None => "Nothing".to_owned(),
                        };
                        s.push_str(&format!(
                            "\n      {} JT.field o {} {def}",
                            if i == 0 { "<$>" } else { "<*>" },
                            string_literal(&f.name)
                        ));
                    }
                    s
                };
                body.push_str(&format!(
                    "\ninstance JC.FromCapsule {tn} where\n  fromValue v = JT.recordFromValue {} v $ {reads}\n  fromCapsuleType _ = Just {info}\n",
                    string_literal(&full)
                ));
                let writes = fields
                    .iter()
                    .map(|(f, acc, _)| {
                        format!("({}, JC.toValue ({acc} x))", string_literal(&f.name))
                    })
                    .collect::<Vec<_>>();
                let writes = if writes.is_empty() {
                    "[]".to_owned()
                } else {
                    format!("\n    [ {}\n    ]", writes.join("\n    , "))
                };
                let x = if fields.is_empty() { "_" } else { "x" };
                body.push_str(&format!(
                    "\ninstance JC.ToCapsule {tn} where\n  toValue {x} = JV.JObject $ HM.fromList{writes}\n  toCapsuleType _ = Just {info}\n"
                ));
                if all_default {
                    body.push_str(&format!(
                        "\n-- | すべてのフィールドが既定値の値\n{default_name} :: {tn}\n{default_name} = either (error . HT.unpack) id (JC.fromValue (JV.JObject HM.empty))\n"
                    ));
                }
                // 定数 (juiz.constants、仕様 §25) は `<型><定数名>` の値にする
                let constants =
                    record_constants(r).map_err(|m| generate_error(format!("{full}: {m}")))?;
                for c in constants.iter() {
                    let acc = accessor(&tn, &c.name);
                    names.add_value(&acc, &format!("constant {full}.{}", c.name))?;
                    exports.push(acc.clone());
                    let paren = |s: String| {
                        if s.starts_with('-') {
                            format!("({s})")
                        } else {
                            s
                        }
                    };
                    let (ty, lit) = match (&c.data_type, &c.value) {
                        (DataType::Boolean, v) => (
                            "Bool",
                            if v.as_bool() == Some(true) {
                                "True"
                            } else {
                                "False"
                            }
                            .to_owned(),
                        ),
                        (DataType::Int, v) => ("HI.Int32", paren(v.to_string())),
                        (DataType::Long, v) => ("HI.Int64", paren(v.to_string())),
                        (DataType::Float, v) => {
                            ("Float", paren(format!("{:?}", v.as_f64().unwrap_or(0.0))))
                        }
                        (DataType::Double, v) => {
                            ("Double", paren(format!("{:?}", v.as_f64().unwrap_or(0.0))))
                        }
                        (_, v) => ("HT.Text", string_literal(v.as_str().unwrap_or(""))),
                    };
                    body.push('\n');
                    body.push_str(&doc_lines(&c.doc, "", '|'));
                    body.push_str(&format!("{acc} :: {ty}\n{acc} = {lit}\n"));
                }
            }
            DataType::Enum(e) => {
                let ctors = e
                    .symbols
                    .iter()
                    .map(|s| {
                        let c = constructor(&tn, s);
                        names.add_type(&c, &format!("symbol {full}.{s}"))?;
                        Ok((s, c))
                    })
                    .collect::<Result<Vec<_>, IdlError>>()?;
                body.push_str(&doc_lines(&e.doc, "", '|'));
                body.push_str(&format!(
                    "data {tn}\n{}\n  deriving (Eq, Ord, Show, Enum, Bounded)\n",
                    ctors
                        .iter()
                        .enumerate()
                        .map(|(i, (_, c))| format!("  {} {c}", if i == 0 { "=" } else { "|" }))
                        .collect::<Vec<_>>()
                        .join("\n")
                ));
                body.push_str(&type_info_code(t, &tn, &info)?);
                let table = ctors
                    .iter()
                    .map(|(s, c)| format!("({}, {c})", string_literal(s)))
                    .collect::<Vec<_>>()
                    .join(", ");
                let def = match &e.default {
                    Some(d) => format!("(Just {})", constructor(&tn, d)),
                    None => "Nothing".to_owned(),
                };
                body.push_str(&format!(
                    "\n-- | 知らない記号は既定値 (仕様 §4)\ninstance JC.FromCapsule {tn} where\n  fromValue = JT.enumFromValue {} [{table}] {def}\n  fromCapsuleType _ = Just {info}\n",
                    string_literal(&full)
                ));
                let cases = ctors
                    .iter()
                    .map(|(s, c)| format!("\n    {c} -> {}", string_literal(s)))
                    .collect::<String>();
                body.push_str(&format!(
                    "\ninstance JC.ToCapsule {tn} where\n  toValue x = JV.JString $ case x of{cases}\n  toCapsuleType _ = Just {info}\n"
                ));
            }
            _ => unreachable!(),
        }
        body.push_str(&format!(
            "\ninstance JT.JuizType {tn} where\n  juizType _ = {info}\n"
        ));
    }

    let mut out = String::new();
    out.push_str("{-# LANGUAGE OverloadedStrings #-}\n{-# OPTIONS_GHC -Wno-unused-imports #-}\n");
    out.push_str(HEADER);
    out.push_str(&format!(
        "-- | 名前空間 {ns} の型 (juiz のデータ型、docs/spec/datatype.md §22)\n"
    ));
    out.push_str(&format!(
        "module {module}\n  ( {}\n  ) where\n\n",
        exports.join("\n  , ")
    ));
    out.push_str(
        "import Prelude (Bool (..), Bounded, Double, Either (..), Enum, Eq, Float, Maybe (..), Ord, Show, either, error, id, pure, ($), (.), (<$>), (<*>))\n",
    );
    out.push_str("import qualified Data.ByteString as HB\n");
    out.push_str("import qualified Data.Int as HI\n");
    out.push_str("import qualified Data.Map.Strict as HM\n");
    out.push_str("import qualified Data.Text as HT\n");
    out.push_str("import qualified Juiz.Capsule as JC\n");
    out.push_str("import qualified Juiz.Type as JT\n");
    out.push_str("import qualified Juiz.Value as JV\n");
    for d in deps.into_iter().flatten() {
        out.push_str(&format!("import qualified {}\n", module_name(d)?));
    }
    out.push_str(&body);
    Ok(out)
}

fn type_info_code(t: &DataType, tn: &str, info: &str) -> Result<String, IdlError> {
    let avro = t.to_avro().map_err(|e| IdlError::Generate {
        message: format!("{}: {e}", t.display_name()),
    })?;
    let avro = serde_json::to_string(&avro).unwrap();
    Ok(format!(
        "\n-- | {tn} の型 (.avsc と同じスキーマ。指紋は libjuiz_sdk が計算する)\n{info} :: JT.TypeInfo\n{info} = JT.unsafeTypeInfo\n  {}\n{{-# NOINLINE {info} #-}}\n",
        string_literal(&avro)
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert_eq!(accessor("Pose2D", "frame_id"), "pose2DFrameId");
        assert_eq!(accessor("Everything", "self"), "everythingSelf");
        assert_eq!(constructor("MotorMode", "idle"), "MotorModeIdle");
        assert_eq!(module_name("robot.geometry").unwrap(), "Robot.Geometry");
        assert!(module_name("robot._x").is_err());
    }

    #[test]
    fn literals() {
        assert_eq!(string_literal("a\"b\\c"), "\"a\\\"b\\\\c\"");
        assert_eq!(string_literal("あ1"), "\"\\12354\\&1\"");
        assert_eq!(
            value_literal(&serde_json::json!({"a": [1, -1.5, null, 18446744073709551615u64]})),
            "JV.JObject (HM.fromList [(\"a\", JV.JArray [JV.JInt 1, JV.JFloat (-1.5), JV.JNull, JV.JUInt 18446744073709551615])])"
        );
    }
}
